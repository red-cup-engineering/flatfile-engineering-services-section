import assert from "node:assert/strict";
import test from "node:test";
import { dK, dF, admitFiniteFrameUniverse, admitValuedSheaf, settledMask, valuedSheafReceipt, powersetFrameReceipt, canonicalDFrameReceipt, allSubsets, subset, finiteSup, meet, join, sameSubset, le } from "../../src/sheaf/topology/d-frame.mjs";

const NAMES = Object.freeze({ bottom: "nothing", positiveOnly: "yes", negativeOnly: "no", top: "both" });

const VALUATION = Object.freeze([
  Object.freeze({ cell: "a", reading: "yes" }),
  Object.freeze({ cell: "b", reading: "both" }),
  Object.freeze({ cell: "c", reading: "no" }),
  Object.freeze({ cell: "d", reading: "nothing" }),
]);

test("dK is exactly the positive-only-or-top cells", () => {
  assert.deepEqual(dK(NAMES, VALUATION).elements, ["a", "b"]);
});

test("dF is exactly the negative-only-or-top cells", () => {
  assert.deepEqual(dF(NAMES, VALUATION).elements, ["b", "c"]);
});

test("settledMask excludes only bottom-charged cells", () => {
  assert.deepEqual(settledMask(NAMES, VALUATION, subset(["a", "b", "c", "d"])).elements, ["a", "b", "c"]);
});

test("valuedSheafReceipt verifies the finite d-frame-valued sheaf laws for a lawful valuation", () => {
  const receipt = valuedSheafReceipt(NAMES, VALUATION);
  assert.equal(receipt.kind, "dFrame.valuedSheaf:witness");
  assert.deepEqual(receipt.positiveSupport.elements, ["a", "b"]);
  assert.deepEqual(receipt.negativeSupport.elements, ["b", "c"]);
});

test("dK/dF/settledMask/valuedSheafReceipt run over ANY caller's own four-valued vocabulary (e.g. FeltOS's claim names), not just one hardcoded set", () => {
  const CLAIM_NAMES = Object.freeze({ bottom: "unknown", positiveOnly: "held", negativeOnly: "denied", top: "contested" });
  const claimValuation = Object.freeze([
    Object.freeze({ cell: "a", reading: "held" }),
    Object.freeze({ cell: "b", reading: "contested" }),
    Object.freeze({ cell: "c", reading: "denied" }),
    Object.freeze({ cell: "d", reading: "unknown" }),
  ]);
  assert.deepEqual(dK(CLAIM_NAMES, claimValuation).elements, ["a", "b"]);
  assert.deepEqual(dF(CLAIM_NAMES, claimValuation).elements, ["b", "c"]);
  const receipt = valuedSheafReceipt(CLAIM_NAMES, claimValuation);
  assert.equal(receipt.kind, "dFrame.valuedSheaf:witness");
});

test("finite-sup frame laws generated by binary joins agree with the exhaustive family test on three marks", () => {
  const universe = ["a", "b", "c"];
  const receipt = powersetFrameReceipt(universe);
  const elements = allSubsets(universe);
  assert.equal(receipt.subsetCount, 8);
  assert.equal(receipt.unionSupLeastUpperBound, true);
  assert.equal(receipt.meetDistributesOverFiniteSup, true);
  // Only the test enumerates all 2^(2^3) families. The production proof
  // checks binary join/bottom plus their inductive finite extension.
  for (let mask = 0; mask < 2 ** elements.length; mask++) {
    const family = elements.filter((_, i) => (mask & (1 << i)) !== 0);
    const sup = finiteSup(family);
    assert.equal(family.every(member => le(member, sup)), true);
    assert.equal(elements.every(upper => !family.every(member => le(member, upper)) || le(sup, upper)), true);
    for (const a of elements) {
      assert.equal(sameSubset(meet(a, sup), finiteSup(family.map(member => meet(a, member)))), true);
    }
  }
});

test("bounded five-mark receipts do not enumerate billions of subset families or overwrite the underlying pure set algebra", () => {
  const universe = ["alpha", "beta", "gamma", "delta", "epsilon"];
  const witness = powersetFrameReceipt(universe);
  assert.equal(witness.subsetCount, 32);
  assert.equal(witness.meetAssociative, true);
  assert.equal(witness.meetDistributesOverFiniteSup, true);
  assert.equal(canonicalDFrameReceipt(universe).conDownwardClosed, true);
  assert.equal(canonicalDFrameReceipt(universe).totUpwardClosed, true);
  const readings = universe.map((cell, index) =>
    Object.freeze({ cell, reading: ["yes", "both", "no", "nothing", "both"][index] }));
  assert.equal(valuedSheafReceipt(NAMES, readings).restrictionPreservesCon, true);
  const six = [...universe, "zeta"];
  assert.equal(allSubsets(six).length, 64, "pure subset utility remains independently useful");
  for (const receipt of [
    () => powersetFrameReceipt(six),
    () => canonicalDFrameReceipt(six),
    () => valuedSheafReceipt(NAMES, six.map(cell => ({cell, reading: "yes"}))),
  ]) assert.throws(receipt, /at most 5 marks/u);
});

test("empty and singleton finite d-frames retain legitimate bottom and top examples", () => {
  for (const universe of [[], ["alpha"]]) {
    const receipt = canonicalDFrameReceipt(universe);
    assert.equal(receipt.conDownwardClosed, true);
    assert.equal(receipt.totUpwardClosed, true);
    assert.equal(receipt.positiveFrame.subsetCount, 2 ** universe.length);
    assert.deepEqual(join(...receipt.totalExample).elements, universe);
    assert.deepEqual(meet(...receipt.consistentExample).elements, []);
  }
});

test("local d-frame sheaf admission refuses contradictions before interpreting unknown marks as bottom", () => {
  for (const valuation of [
    [{cell:"a",reading:"yes"}, {cell:"a",reading:"no"}],
    [{cell:"a",reading:"unknown-but-not-bottom"}],
    [{cell:"a",reading:"yes"}, {cell:"a",reading:"yes"}],
    [{cell:7,reading:"yes"}],
    [{cell:"a",reading:false}],
  ]) {
    assert.throws(() => valuedSheafReceipt(NAMES,valuation), /duplicate valuation cell|admitted FOUR reading/u);
  }
  for (const invalid of [
    {bottom:"nothing",positiveOnly:"yes",negativeOnly:"no",top:"yes"},
    {bottom:"nothing",positiveOnly:"yes",negativeOnly:"no"},
    {bottom:0,positiveOnly:"yes",negativeOnly:"no",top:"both"},
  ]) {
    assert.throws(() => valuedSheafReceipt(invalid,VALUATION), /distinct four-valued reading vocabulary/u);
    assert.throws(() => dK(invalid,VALUATION), /distinct four-valued reading vocabulary/u);
  }
  assert.throws(() => dF(NAMES,[{cell:"a",reading:"not-an-admitted-reading"}]),/admitted FOUR reading/u);
  assert.throws(() => settledMask(NAMES,[{cell:"a",reading:"yes"}, {cell:"a",reading:"both"}],subset(["a"])),/duplicate valuation cell/u);
  assert.throws(() => subset([{"not":"a-token"}]),/nonempty strings/u);
  assert.deepEqual(valuedSheafReceipt(NAMES,VALUATION).positiveSupport.elements,["a","b"],
    "admitted ordinary FOUR valuations keep their exact prior positive support");
});

test("pure pre-payment admission matches finite frame and sheaf computation restrictions exactly", () => {
  const admitted = admitFiniteFrameUniverse(["beta", "alpha"]);
  assert.deepEqual(admitted, ["alpha","beta"]);
  assert.equal(powersetFrameReceipt(admitted).subsetCount, 4);
  const local = admitValuedSheaf(NAMES, VALUATION, subset(["a","b"]));
  assert.deepEqual(local.universe, ["a","b","c","d"]);
  assert.deepEqual(local.clopen.elements, ["a","b"]);
  assert.deepEqual(valuedSheafReceipt(NAMES, VALUATION,local.clopen).positiveSupport.elements, ["a","b"]);
  assert.throws(() => admitFiniteFrameUniverse(["a","b","c","d","e","f"]),/at most 5 marks/u);
  assert.throws(() => admitValuedSheaf(NAMES,[{cell:"a",reading:"yes"},{cell:"a",reading:"no"}]),/duplicate valuation cell/u);
  assert.throws(() => admitValuedSheaf(NAMES,VALUATION,subset(["foreign"])),/outside the universe/u);
});
