"""Closure operators on cross-fiber predication valuations.

Realizes corpus morphism: ``closure-operator`` (the family ``cl = (cl_p)_p``
on predication-fiber-algebras, satisfying monotonicity, inflation,
idempotence, and ``𝒞``-naturality).

The realisation here covers the **quantifier-free fragment of the
closure-rule language** — the Scott-continuous, strict-regime case
sufficient to drive the corpus's finite-base examples (relational
database, friendship-four-generators, multi-agent epistemic). Rules with
universally-quantified antecedents over infinite domains, which generate
the non-Scott-continuous behaviours of the transfinite-bounded and
aperiodic regimes, are out of scope here; they require transfinite
iteration which the strict orbit driver does not handle.

A rule has shape::

    ∀ y₁ … y_k ∈ E.    ⋀_i v(q_i)(s_i(ȳ), o_i(ȳ)) ≥_k V_i
                       ⇒ v(p)(s(ȳ), o(ȳ)) ≥_k V

Free entity variables ``y₁, …, y_k`` range over the entity set. Antecedent
atoms ``v(q)(s, o) ≥_k V`` test that the current cross-fiber valuation
asserts at least value ``V`` (in the knowledge order) at cell
``(s, o)`` of the fiber over predicate ``q``. The consequent commits a
``≥_k V`` lower bound on the target cell — implemented as a
knowledge-join with ``V`` of the existing cell value.

Because the antecedent is quantifier-free over an explicit free-variable
list, the rule fires per-instantiation of the free variables; for finite
``E`` the per-step rule application is a finite enumeration.

``𝒞``-naturality (closure-operator axiom 4) is **not enforced at
construction**: a rule list can violate naturality without being detected
syntactically. The caller can verify naturality on a fixed-point via
:meth:`PredicateCategory.is_natural`. A future hardening could check
naturality on every closure step.
"""

from __future__ import annotations

from collections.abc import Hashable, Mapping
from dataclasses import dataclass, field
from itertools import product
from typing import Generic, TypeVar

from .._realizes import realizes
from ..algebra.twist_product import TwistBilattice
from ..predication.fiber_valuation import FiberValuation
from ..predication.predicate_category import PredicateCategory

T = TypeVar("T", bound=Hashable)

# A free variable name (string) or a literal entity in ``E`` — the rule
# language allows both. Literal entities at antecedent or consequent slots
# pin the rule to a specific cell.
EntityTerm = Hashable
CrossFiberValuation = Mapping[Hashable, FiberValuation[T]]


@dataclass(frozen=True)
class CellAtom(Generic[T]):
    """Antecedent atom ``v(predicate)(subject, object) ≥_k threshold``.

    ``subject`` and ``object`` are :class:`EntityTerm` — either an entity
    in ``E`` (literal) or a string naming a free variable bound by the
    enclosing rule. Free-variable bindings come from the rule's
    free-variable list.
    """

    predicate: Hashable
    subject: EntityTerm
    object: EntityTerm
    threshold: tuple[T, T]


@dataclass(frozen=True)
class CellConsequent(Generic[T]):
    """Consequent ``v(predicate)(subject, object) ≥_k value`` of a rule."""

    predicate: Hashable
    subject: EntityTerm
    object: EntityTerm
    value: tuple[T, T]


@dataclass(frozen=True)
class FiberClosureRule(Generic[T]):
    """A quantifier-free closure rule with explicit free entity variables.

    The rule fires once per assignment of ``free_vars`` to entities in
    ``E``. For each assignment, every cell atom in ``antecedents`` is
    evaluated against the current cross-fiber valuation; if all atoms
    hold, the consequent commits its value to the target cell.
    """

    antecedents: tuple[CellAtom[T], ...]
    consequent: CellConsequent[T]
    free_vars: tuple[str, ...] = ()

    def _instantiate_term(
        self, term: EntityTerm, binding: Mapping[str, Hashable]
    ) -> Hashable:
        if isinstance(term, str) and term in binding:
            return binding[term]
        return term


@realizes("morphisms/closure-operator")
@dataclass(frozen=True)
class ClosureOperator(Generic[T]):
    """Closure operator on cross-fiber valuations over a predicate category.

    Generated by a finite rule list. The :meth:`apply` method performs a
    single closure step: for every rule and every free-variable
    instantiation, fire the consequent's lower-bound commitment on the
    appropriate fiber cell. :meth:`saturate` iterates :meth:`apply` until
    a fixed point is reached, yielding the closure of the input. The
    closure ordinal of the saturation orbit is exposed by
    :meth:`closure_ordinal`.
    """

    category: PredicateCategory
    bilattice: TwistBilattice[T]
    bottom: tuple[T, T]
    rules: tuple[FiberClosureRule[T], ...] = field(default_factory=tuple)
    max_steps: int = 10_000

    def __post_init__(self) -> None:
        # Sanity-check rule predicates are objects of the category.
        predicates = set(self.category.predicates)
        for rule in self.rules:
            if rule.consequent.predicate not in predicates:
                raise ValueError(
                    f"rule consequent predicate "
                    f"{rule.consequent.predicate!r} not in category"
                )
            for atom in rule.antecedents:
                if atom.predicate not in predicates:
                    raise ValueError(
                        f"rule antecedent predicate "
                        f"{atom.predicate!r} not in category"
                    )

    def _empty_valuation(self) -> dict[Hashable, FiberValuation[T]]:
        return {
            p: FiberValuation(
                bilattice=self.bilattice,
                entities=self.category.entities,
                bottom=self.bottom,
                cells={},
                dom=self.category.dom_of(p),
            )
            for p in self.category.predicates
        }

    def _ensure_full_valuation(
        self, v: CrossFiberValuation[T]
    ) -> dict[Hashable, FiberValuation[T]]:
        """Return a copy with every category predicate present (empty fiber default)."""
        out = self._empty_valuation()
        for p, fiber in v.items():
            if p not in out:
                raise KeyError(
                    f"valuation has fiber for {p!r} which is not in the category"
                )
            out[p] = fiber
        return out

    def apply(
        self, valuation: CrossFiberValuation[T]
    ) -> dict[Hashable, FiberValuation[T]]:
        """One closure step: fire every rule at every free-variable instantiation.

        Inflation is automatic — the consequent's commitment is joined
        (in ``≤_k``) with the existing cell value, so the result strictly
        dominates the input under ``≤_k``.
        """
        current = self._ensure_full_valuation(valuation)
        # Build a working dict of cells per predicate.
        working: dict[Hashable, dict[tuple[Hashable, Hashable], tuple[T, T]]] = {
            p: dict(current[p].cells) for p in current
        }
        E_list = list(self.category.entities)
        bil = self.bilattice
        for rule in self.rules:
            for assignment in product(E_list, repeat=len(rule.free_vars)):
                binding = dict(zip(rule.free_vars, assignment, strict=True))
                if not self._antecedents_hold(rule, binding, current):
                    continue
                # Apply consequent.
                cons = rule.consequent
                s = rule._instantiate_term(cons.subject, binding)
                o = rule._instantiate_term(cons.object, binding)
                if s not in self.category.entities or o not in self.category.entities:
                    continue
                # Respect predicate domain: skip cells outside dom(predicate).
                dom = self.category.dom_of(cons.predicate)
                if (s, o) not in dom:
                    continue
                existing = working[cons.predicate].get((s, o), self.bottom)
                joined = bil.knowledge_join(existing, cons.value)
                working[cons.predicate][(s, o)] = joined
        # Wrap each predicate's working dict as a FiberValuation.
        return {
            p: FiberValuation(
                bilattice=self.bilattice,
                entities=self.category.entities,
                bottom=self.bottom,
                cells=cells,
                dom=self.category.dom_of(p),
            )
            for p, cells in working.items()
        }

    def _antecedents_hold(
        self,
        rule: FiberClosureRule[T],
        binding: Mapping[str, Hashable],
        valuation: Mapping[Hashable, FiberValuation[T]],
    ) -> bool:
        bil = self.bilattice
        for atom in rule.antecedents:
            s = rule._instantiate_term(atom.subject, binding)
            o = rule._instantiate_term(atom.object, binding)
            if s not in self.category.entities or o not in self.category.entities:
                return False
            current_value = valuation[atom.predicate].get(s, o)
            if not bil.knowledge_leq(atom.threshold, current_value):
                return False
        return True

    def saturate(
        self, valuation: CrossFiberValuation[T]
    ) -> dict[Hashable, FiberValuation[T]]:
        """Iterate :meth:`apply` until a fixed point. Returns the closure."""
        current = self._ensure_full_valuation(valuation)
        for _ in range(self.max_steps):
            nxt = self.apply(current)
            if _eq_cross(nxt, current):
                return current
            current = nxt
        raise RuntimeError(
            f"closure orbit did not stabilise within {self.max_steps} steps "
            "(non-strict regime, or rule loop)"
        )

    def forward_trajectory(
        self, valuation: CrossFiberValuation[T]
    ) -> list[dict[Hashable, FiberValuation[T]]]:
        """The full ``≤_k``-monotone orbit ``v_0, v_1, …, v_κ`` to closure."""
        traj: list[dict[Hashable, FiberValuation[T]]] = [
            self._ensure_full_valuation(valuation)
        ]
        for _ in range(self.max_steps):
            nxt = self.apply(traj[-1])
            if _eq_cross(nxt, traj[-1]):
                return traj
            traj.append(nxt)
        raise RuntimeError(
            f"closure orbit did not stabilise within {self.max_steps} steps "
            "(non-strict regime, or rule loop)"
        )

    def closure_ordinal(self, valuation: CrossFiberValuation[T]) -> int:
        """Smallest ``k`` with ``cl^k(v) = cl^{k+1}(v)``. Strict regime only."""
        return len(self.forward_trajectory(valuation)) - 1


def _eq_cross(
    a: Mapping[Hashable, FiberValuation[T]],
    b: Mapping[Hashable, FiberValuation[T]],
) -> bool:
    if set(a) != set(b):
        return False
    for p in a:
        if a[p] != b[p]:
            return False
    return True


