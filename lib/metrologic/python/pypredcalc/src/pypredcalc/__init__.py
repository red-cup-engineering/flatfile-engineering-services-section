"""pypredcalc — pure-math primitives for predication-native computation.

Layered subpackages:

- `algebra`      — bilattices, twist-products, and residuated lattices
- `predication`  — predication cells, fibers, fibrations, hyperdoctrines,
  closure systems, settling, and parameter bases
- `combinatorics` — posets, simplicial complexes, closure-rule systems
- `topology`     — finite Alexandrov/Priestley structures and transfinite
  cell complexes
- `lattice`      — frames, frame morphisms, d-frames
- `sheaf`        — Z-cohomology, cellular and frame-valued sheaves
- `dynamics`     — substitution matrices, named corpus instances
- `_linalg`      — internal Fraction-native linear algebra (zero-dep)

Zero runtime dependencies; sympy is only required for the optional `[symbolic]`
extra (exact symbolic Perron eigenvalues, etc.).
"""

