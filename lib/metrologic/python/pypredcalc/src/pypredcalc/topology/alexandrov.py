"""Finite Alexandrov topology on a preordered set.

Realizes corpus object: `alexandrov-topology`.

For a finite preorder ``(X, ≤)``, the Alexandrov topology has as open
sets exactly the **up-sets** (sets ``U`` with ``x ∈ U, x ≤ y ⇒ y ∈ U``).
On finite carriers this is a bijection: every topology in which arbitrary
intersections of opens are open arises this way, and the recovered
preorder is the **specialisation preorder** ``x ≤ y iff x ∈ cl({y})``.

This module realises that bijection in both directions and provides
the up-set / down-set / minimal-open / closure operations.
"""

from __future__ import annotations

from collections.abc import Callable, Hashable
from dataclasses import dataclass
from typing import Generic, TypeVar

from .._realizes import realizes

T = TypeVar("T", bound=Hashable)


@realizes("objects/alexandrov-topology")
@dataclass(frozen=True)
class AlexandrovTopology(Generic[T]):
    """Finite Alexandrov space induced by a preorder ``leq``."""

    carrier: frozenset[T]
    leq: Callable[[T, T], bool]

    def __post_init__(self) -> None:
        if not self.carrier:
            raise ValueError("Alexandrov carrier must be non-empty")
        for a in self.carrier:
            if not self.leq(a, a):
                raise ValueError(f"preorder: reflexivity fails at {a!r}")
            for b in self.carrier:
                for c in self.carrier:
                    if self.leq(a, b) and self.leq(b, c) and not self.leq(a, c):
                        raise ValueError(
                            f"preorder: transitivity fails at ({a!r}, {b!r}, {c!r})"
                        )

    def is_up_set(self, s: frozenset[T]) -> bool:
        """Whether ``s`` is upward-closed under ``leq`` — i.e. an open set."""
        if not s.issubset(self.carrier):
            raise ValueError("set must be a subset of the carrier")
        return all(
            (y in s) for x in s for y in self.carrier if self.leq(x, y)
        )

    def is_open(self, s: frozenset[T]) -> bool:
        """An Alexandrov-open set is exactly an up-set."""
        return self.is_up_set(s)

    def is_closed(self, s: frozenset[T]) -> bool:
        """A closed set is a down-set (complement of an up-set)."""
        if not s.issubset(self.carrier):
            raise ValueError("set must be a subset of the carrier")
        return all(
            (y in s) for x in s for y in self.carrier if self.leq(y, x)
        )

    def minimal_open(self, x: T) -> frozenset[T]:
        """Smallest open containing ``x`` — the principal up-set ``↑x``."""
        if x not in self.carrier:
            raise ValueError(f"{x!r} not in carrier")
        return frozenset(y for y in self.carrier if self.leq(x, y))

    def closure(self, s: frozenset[T]) -> frozenset[T]:
        """Topological closure: the down-set generated by ``s``."""
        if not s.issubset(self.carrier):
            raise ValueError("set must be a subset of the carrier")
        return frozenset(
            y for y in self.carrier if any(self.leq(y, x) for x in s)
        )

    def opens(self) -> frozenset[frozenset[T]]:
        """Enumerate every open set (= every up-set) of the topology.

        For an n-element carrier this is at most 2^n; intended for small
        analytical use, not enumeration of large spaces.
        """
        elements = sorted(self.carrier, key=hash)
        n = len(elements)
        result: set[frozenset[T]] = set()
        for mask in range(1 << n):
            subset = frozenset(elements[i] for i in range(n) if mask & (1 << i))
            if self.is_up_set(subset):
                result.add(subset)
        return frozenset(result)


def specialisation_preorder(
    carrier: frozenset[T], opens: frozenset[frozenset[T]]
) -> AlexandrovTopology[T]:
    """Recover the Alexandrov topology from its lattice of opens.

    Defines ``x ≤ y`` iff every open containing ``x`` contains ``y``
    (equivalently, ``x ∈ cl({y})`` in the dual convention).

    Validates that ``opens`` is a topology of subsets of ``carrier``:
    each open is a subset of ``carrier``, both ``∅`` and ``carrier``
    appear, and the family is closed under finite intersection and
    arbitrary union (Alexandrov axiom).
    """
    if not carrier:
        raise ValueError("carrier must be non-empty")
    for u in opens:
        if not u.issubset(carrier):
            raise ValueError(f"open {set(u)!r} is not a subset of carrier")
    if frozenset() not in opens:
        raise ValueError("opens must contain the empty set")
    if carrier not in opens:
        raise ValueError("opens must contain the whole carrier")
    for u in opens:
        for v in opens:
            if (u & v) not in opens:
                raise ValueError(
                    f"opens not closed under intersection: {set(u)!r} ∩ {set(v)!r}"
                )
    # Alexandrov: arbitrary unions; check pairwise (sufficient for finite case).
    for u in opens:
        for v in opens:
            if (u | v) not in opens:
                raise ValueError(
                    f"opens not closed under union: {set(u)!r} ∪ {set(v)!r}"
                )
    table = {
        (x, y): all((y in u) for u in opens if x in u)
        for x in carrier
        for y in carrier
    }
    return AlexandrovTopology(carrier=carrier, leq=lambda a, b: table[(a, b)])
