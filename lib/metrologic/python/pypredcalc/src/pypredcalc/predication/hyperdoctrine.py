T = TypeVar("T", bound=Hashable)


@dataclass(frozen=True)
class PredicationHyperdoctrineWitness(Generic[T]):
    """Aggregate A/B witness for a predication hyperdoctrine.

    The predication hyperdoctrine contains the A1-A3 fibration layer plus
    B1-B4 hyperdoctrine laws. This witness keeps those components separate
    so callers can inspect the mathematical layer that failed.
    """

    hyperdoctrine: PredicationHyperdoctrine[T]
    fibration: PredicationFibrationWitness[T]
    quantifier_adjunctions: tuple[QuantifierAdjunctionWitness[T], ...]
    frobenius: tuple[FrobeniusWitness[T], ...]
    beck_chevalley: tuple[BeckChevalleyWitness[T], ...]
    comprehension: tuple[ComprehensionAdjunctionWitness[T], ...]

    @property
    def b1(self) -> tuple[QuantifierAdjunctionWitness[T], ...]:
        return self.quantifier_adjunctions

    @property
    def b2(self) -> tuple[FrobeniusWitness[T], ...]:
        return self.frobenius

    @property
    def b3(self) -> tuple[BeckChevalleyWitness[T], ...]:
        return self.beck_chevalley

    @property
    def b4(self) -> tuple[ComprehensionAdjunctionWitness[T], ...]:
        return self.comprehension

    @property
    def holds(self) -> bool:
        if not self.fibration.holds:
            return False
        for group in (self.b1, self.b2, self.b3, self.b4):
            if not all(witness.holds for witness in group):
                return False
        return True

    @property
    def failures(self) -> tuple[object, ...]:
        failures: list[object] = []
        if not self.fibration.holds:
            failures.append(self.fibration)
        for group in (self.b1, self.b2, self.b3, self.b4):
            failures.extend(witness for witness in group if not witness.holds)
        return tuple(failures)

    def __bool__(self) -> bool:
        return self.holds


@realizes("objects/predication-hyperdoctrine")
@dataclass(frozen=True)
class PredicationHyperdoctrine(Generic[T]):
    """The predication hyperdoctrine over ``(L, C, E)``.

    Wraps the explicit :class:`PredicationFibration` generated by a
    :class:`PredicateCategory` and a twist bilattice ``L^⋈``. The aggregate
    exposes the hyperdoctrine surface:

    - :meth:`fiber` — the constant-bottom element of ``A_p``.
    - :meth:`f_star` — reindexing along any predicate morphism.
    - :meth:`exists_k`, :meth:`exists_t`, :meth:`forall_k`,
      :meth:`forall_t` — the four quantifier adjoints (B1k/B1t).
    - :meth:`extension_t`, :meth:`extension_k` — the comprehension
      schema's left adjoints (B4).
    - :meth:`comprehension_t`, :meth:`comprehension_k` — the right
      adjoints (B4).

    Every method routes through an existing primitive; the aggregate
    only fixes ``L`` and ``dom`` so the caller does not have to pass
    them at every site.
    """

    category: PredicateCategory
    bilattice: TwistBilattice[T]

    # ---- direct accessors -------------------------------------------------

    @property
    def fibration(self) -> PredicationFibration[T]:
        """The A1-A3 predication fibration under this hyperdoctrine."""
        return PredicationFibration(self.category, self.bilattice)

    def predicates(self) -> Iterator[Hashable]:
        """Iterate the object set ``Π = Ob(𝒞)``."""
        return iter(self.category.predicates)

    def dom(self, predicate: Hashable) -> frozenset[tuple[Hashable, Hashable]]:
        """The designated domain ``dom(p) ⊆ E × E`` of ``p``."""
        return self.fibration.dom(predicate)

    def fiber(self, predicate: Hashable) -> FiberValuation[T]:
        """The constant-``⊥_k`` element of ``A_p`` — the empty fiber.

        Useful as a starting point for building fibers cell-by-cell or
        as the unit of ``∨_k``.
        """
        return self.fibration.fiber(predicate)

    # ---- hyperdoctrine surface --------------------------------------------

    def check_axioms(self) -> PredicationHyperdoctrineWitness[T]:
        """Check the sampled predication-hyperdoctrine law package.

        The package keeps the corpus layers explicit:

        - A1-A3: the underlying predication fibration.
        - B1: the four quantifier adjunctions for each generator.
        - B2: knowledge/truth Frobenius reciprocity for each generator.
        - B3: Beck-Chevalley for same-target generator pairs.
        - B4: classical and paraconsistent comprehension for specializations.
        """
        generators = tuple(self.category.generators)
        specializations = tuple(
            generator
            for generator in generators
            if isinstance(generator, PredicateSpecialization)
        )
        return PredicationHyperdoctrineWitness(
            hyperdoctrine=self,
            fibration=self.fibration.check_axioms(),
            quantifier_adjunctions=tuple(
                self.quantifier_adjunctions(generator)
                for generator in generators
            ),
            frobenius=tuple(
                self.frobenius(generator)
                for generator in generators
            ),
            beck_chevalley=tuple(
                self.beck_chevalley(f, g)
                for f in generators
                for g in generators
                if f.target == g.target
            ),
            comprehension=tuple(
                self.comprehension_adjunction(
                    specialization,
                    schema=schema,
                )
                for specialization in specializations
                for schema in ("classical", "paraconsistent")
            ),
        )

    def f_star(
        self, f: PredicateMorphism, fiber: FiberValuation[T]
    ) -> FiberValuation[T]:
        """Reindexing ``f^* : A_target → A_source``.

        The fiber must live over ``f.target``; the result lives over
        ``f.source`` and has ``dom == dom(f.source)`` for the canonical
        generator classes.
        """
        return self.fibration.f_star(f, fiber)

    def exists_k(
        self, f: PredicateMorphism, fiber: FiberValuation[T]
    ) -> FiberValuation[T]:
        """``∃_f^k : A_source → A_target``. Left adjoint to ``f^*`` in ``≤_k``."""
        self._require_source_fiber(f, fiber)
        return f.existential_k(fiber, self.dom(f.target))

    def exists_t(
        self, f: PredicateMorphism, fiber: FiberValuation[T]
    ) -> FiberValuation[T]:
        """``∃_f^t : A_source → A_target``. Left adjoint to ``f^*`` in ``≤_t``."""
        self._require_source_fiber(f, fiber)
        return f.existential_t(fiber, self.dom(f.target))

    def forall_k(
        self, f: PredicateMorphism, fiber: FiberValuation[T]
    ) -> FiberValuation[T]:
        """``∀_f^k : A_source → A_target``. Right adjoint to ``f^*`` in ``≤_k``."""
        self._require_source_fiber(f, fiber)
        return f.universal_k(fiber, self.dom(f.target))

    def forall_t(
        self, f: PredicateMorphism, fiber: FiberValuation[T]
    ) -> FiberValuation[T]:
        """``∀_f^t : A_source → A_target``. Right adjoint to ``f^*`` in ``≤_t``."""
        self._require_source_fiber(f, fiber)
        return f.universal_t(fiber, self.dom(f.target))

    def quantifier_adjunctions(
        self,
        f: PredicateMorphism,
        *,
        source_samples: Sequence[FiberValuation[T]] | None = None,
        target_samples: Sequence[FiberValuation[T]] | None = None,
    ) -> QuantifierAdjunctionWitness[T]:
        """Sample the B1k/B1t adjunction laws for one predicate morphism."""
        sources = (
            tuple(source_samples)
            if source_samples is not None
            else self._samples_for(f.source)
        )
        targets = (
            tuple(target_samples)
            if target_samples is not None
            else self._samples_for(f.target)
        )
        for source in sources:
            self._require_source_fiber(f, source)
        for target in targets:
            self._require_target_fiber(f, target)

        checks: list[QuantifierAdjunctionCheck[T]] = []
        for source in sources:
            for target in targets:
                checks.extend(
                    (
                        QuantifierAdjunctionCheck(
                            morphism=f,
                            adjunction="exists_k",
                            source=source,
                            target=target,
                            left_holds=self.exists_k(f, source).knowledge_leq(target),
                            right_holds=source.knowledge_leq(
                                self.f_star(f, target)
                            ),
                        ),
                        QuantifierAdjunctionCheck(
                            morphism=f,
                            adjunction="forall_k",
                            source=source,
                            target=target,
                            left_holds=self.f_star(f, target).knowledge_leq(source),
                            right_holds=target.knowledge_leq(
                                self.forall_k(f, source)
                            ),
                        ),
                        QuantifierAdjunctionCheck(
                            morphism=f,
                            adjunction="exists_t",
                            source=source,
                            target=target,
                            left_holds=self.exists_t(f, source).truth_leq(target),
                            right_holds=source.truth_leq(self.f_star(f, target)),
                        ),
                        QuantifierAdjunctionCheck(
                            morphism=f,
                            adjunction="forall_t",
                            source=source,
                            target=target,
                            left_holds=self.f_star(f, target).truth_leq(source),
                            right_holds=target.truth_leq(
                                self.forall_t(f, source)
                            ),
                        ),
                    )
                )
        return QuantifierAdjunctionWitness(
            hyperdoctrine=self,
            morphism=f,
            checks=tuple(checks),
        )

    def frobenius(
        self,
        f: PredicateMorphism,
        *,
        target_samples: Sequence[FiberValuation[T]] | None = None,
        source_samples: Sequence[FiberValuation[T]] | None = None,
    ) -> FrobeniusWitness[T]:
        """Sample B2k/B2t Frobenius reciprocity for one predicate morphism."""
        targets = (
            tuple(target_samples)
            if target_samples is not None
            else self._samples_for(f.target)
        )
        sources = (
            tuple(source_samples)
            if source_samples is not None
            else self._samples_for(f.source)
        )
        for target in targets:
            self._require_target_fiber(f, target)
        for source in sources:
            self._require_source_fiber(f, source)

        checks: list[FrobeniusCheck[T]] = []
        for target in targets:
            for source in sources:
                lhs_k = self.exists_k(
                    f,
                    self.f_star(f, target).knowledge_meet(source),
                )
                rhs_k = target.knowledge_meet(self.exists_k(f, source))
                lhs_t = self.exists_t(
                    f,
                    self.f_star(f, target).truth_meet(source),
                )
                rhs_t = target.truth_meet(self.exists_t(f, source))
                checks.extend(
                    (
                        FrobeniusCheck(
                            morphism=f,
                            order="k",
                            target=target,
                            source=source,
                            lhs=lhs_k,
                            rhs=rhs_k,
                        ),
                        FrobeniusCheck(
                            morphism=f,
                            order="t",
                            target=target,
                            source=source,
                            lhs=lhs_t,
                            rhs=rhs_t,
                        ),
                    )
                )
        return FrobeniusWitness(
            hyperdoctrine=self,
            morphism=f,
            checks=tuple(checks),
        )

    def fusion_frobenius(
        self,
        f: PredicateMorphism,
        *,
        target_samples: Sequence[FiberValuation[T]] | None = None,
        source_samples: Sequence[FiberValuation[T]] | None = None,
    ) -> FusionFrobeniusWitness[T]:
        """Sample the non-axiomatic Frobenius identity for fusion ``⊙``.

        This is expected to fail for specialization and projections when
        off-image target cells exist; it holds for bijective generators such
        as converse and identity.
        """
        targets, sources = self._fusion_frobenius_samples(
            f,
            target_samples=target_samples,
            source_samples=source_samples,
        )
        checks: list[FusionFrobeniusCheck[T]] = []
        for target in targets:
            self._require_target_fiber(f, target)
        for source in sources:
            self._require_source_fiber(f, source)
        for target in targets:
            for source in sources:
                lhs = self.exists_k(
                    f,
                    self.f_star(f, target).fusion(source),
                )
                rhs = target.fusion(self.exists_k(f, source))
                checks.append(
                    FusionFrobeniusCheck(
                        morphism=f,
                        target=target,
                        source=source,
                        lhs=lhs,
                        rhs=rhs,
                    )
                )
        return FusionFrobeniusWitness(
            hyperdoctrine=self,
            morphism=f,
            checks=tuple(checks),
        )

    def beck_chevalley(
        self,
        f: PredicateMorphism,
        g: PredicateMorphism,
        fibers_at_g_source: Sequence[Mapping[Hashable, tuple[T, T]]] | None = None,
    ) -> BeckChevalleyWitness[T]:
        """Witness B3 Beck-Chevalley commutation for parallel maps."""
        if f.target != g.target:
            raise ValueError("Beck-Chevalley requires f.target == g.target")
        f_index = self.index_map(f)
        g_index = self.index_map(g)
        if fibers_at_g_source is None:
            samples: tuple[Mapping[Hashable, tuple[T, T]], ...] = (
                {
                    cell: value
                    for cell, value in self.fiber(g.source).cells.items()
                },
            )
        else:
            samples = tuple(
                {cell: value for cell, value in sample.items()}
                for sample in fibers_at_g_source
            )
        for sample in samples:
            stray = set(sample) - set(g_index.source)
            if stray:
                raise ValueError(
                    f"fiber sample carries cells outside dom({g.source!r}): "
                    f"{stray!r}"
                )
        return beck_chevalley_witness(f_index, g_index, samples)

    # ---- comprehension (B4) -----------------------------------------------

    def extension_t(self, g: PredicateSpecialization) -> FiberValuation[T]:
        """``Ext^t(g) = ∃_g^t(1_q^t)`` — characteristic in ``≤_t`` of ``dom(q)``."""
        return _extension_t(
            g,
            self.bilattice,
            entities=self.category.entities,
            dom_p=self.dom(g.target),
        )

    def extension_k(self, g: PredicateSpecialization) -> FiberValuation[T]:
        """``Ext^k(g) = ∃_g^k(1_q^k)`` — characteristic in ``≤_k`` of ``dom(q)``."""
        return _extension_k(
            g,
            self.bilattice,
            entities=self.category.entities,
            dom_p=self.dom(g.target),
        )

    def comprehension_t(
        self, predicate: Hashable, psi: FiberValuation[T]
    ) -> PredicateSpecialization:
        """``{p : ψ}_t`` — specialization with ``sub_support = ψ^{-1}(t)``.

        Right adjoint of :meth:`extension_t`.
        """
        return _comprehension_t(predicate, self.dom(predicate), psi)

    def comprehension_k(
        self, predicate: Hashable, psi: FiberValuation[T]
    ) -> PredicateSpecialization:
        """``{p : ψ}_⊤`` — specialization with ``sub_support = ψ^{-1}(⊤)``.

        Right adjoint of :meth:`extension_k`.
        """
        return _comprehension_k(predicate, self.dom(predicate), psi)

    def index_map(self, morphism: PredicateMorphism) -> IndexMap[T]:
        """Reduce a predicate morphism to its cellwise ``IndexMap``."""
        return self.fibration.index_map(morphism)

    def comprehension_adjunction(
        self,
        g: PredicateSpecialization,
        *,
        psis: Sequence[FiberValuation[T]] | None = None,
        schema: str,
    ) -> ComprehensionAdjunctionWitness[T]:
        """Sample one B4 Lawvere comprehension adjunction for ``g``."""
        self._require_specialization(g)
        psi_samples = tuple(psis) if psis is not None else self._samples_for(g.target)
        for psi in psi_samples:
            self._require_target_fiber(g, psi)
        return comprehension_adjunction_witness(
            g,
            psi_samples,
            self.bilattice,
            entities=self.category.entities,
            dom_p=self.dom(g.target),
            schema=schema,
        )

    # ---- helpers ----------------------------------------------------------

    def _require_specialization(self, g: PredicateSpecialization) -> None:
        if g.source not in self.category.predicates:
            raise KeyError(f"specialization source {g.source!r} not in category")
        if g.target not in self.category.predicates:
            raise KeyError(f"specialization target {g.target!r} not in category")
        if g.sub_support != self.dom(g.source):
            raise ValueError("specialization sub_support must equal dom(source)")
        if not g.sub_support <= self.dom(g.target):
            raise ValueError("specialization sub_support must lie in dom(target)")

    def _require_source_fiber(
        self, f: PredicateMorphism, fiber: FiberValuation[T]
    ) -> None:
        expected = self.dom(f.source)
        if fiber.dom != expected:
            raise ValueError(
                f"fiber.dom {sorted(fiber.dom)!r} does not match "
                f"dom({f.source!r}) = {sorted(expected)!r} required for "
                f"adjoints along {f!r}"
            )

    def _require_target_fiber(
        self, f: PredicateMorphism, fiber: FiberValuation[T]
    ) -> None:
        expected = self.dom(f.target)
        if fiber.dom != expected:
            raise ValueError(
                f"fiber.dom {sorted(fiber.dom)!r} does not match "
                f"dom({f.target!r}) = {sorted(expected)!r} required for "
                f"reindexing along {f!r}"
            )

    def _samples_for(self, predicate: Hashable) -> tuple[FiberValuation[T], ...]:
        bottom = self.fiber(predicate)
        dom = tuple(sorted(self.dom(predicate), key=repr))
        if not dom:
            return (bottom,)
        cell = dom[0]
        return (
            bottom,
            self._one_cell(predicate, cell, self.bilattice.truth_top()),
            self._one_cell(predicate, cell, self.bilattice.knowledge_top()),
        )

    def _one_cell(
        self,
        predicate: Hashable,
        cell: tuple[Hashable, Hashable],
        value: tuple[T, T],
    ) -> FiberValuation[T]:
        return FiberValuation(
            bilattice=self.bilattice,
            entities=self.category.entities,
            bottom=self.bilattice.knowledge_bottom(),
            cells={cell: value},
            dom=self.dom(predicate),
        )

    def _fusion_frobenius_samples(
        self,
        f: PredicateMorphism,
        *,
        target_samples: Sequence[FiberValuation[T]] | None,
        source_samples: Sequence[FiberValuation[T]] | None,
    ) -> tuple[tuple[FiberValuation[T], ...], tuple[FiberValuation[T], ...]]:
        targets = (
            tuple(target_samples)
            if target_samples is not None
            else self._samples_for(f.target)
        )
        sources = (
            tuple(source_samples)
            if source_samples is not None
            else self._samples_for(f.source)
        )
        if target_samples is not None or source_samples is not None:
            return targets, sources

        index = self.index_map(f)
        off_image = tuple(
            sorted(index.target - frozenset(index.phi.values()), key=repr)
        )
        if not off_image:
            return targets, sources
        off_image_cell = cast(tuple[Hashable, Hashable], off_image[0])
        counter_target = self._one_cell(
            f.target,
            off_image_cell,
            self.bilattice.truth_bottom(),
        )
        return (*targets, counter_target), sources


