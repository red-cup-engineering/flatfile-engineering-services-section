"""Predication hyperdoctrine — aggregate of B1-B4 over a predicate category.

The predicate-category-and-fiber-algebra primitives realised in this
package give the *pieces* of the corpus's predication hyperdoctrine:
the four generator classes carry their own pullback ``f^*`` and the
four adjoints ``∃_f^k``, ``∃_f^t``, ``∀_f^k``, ``∀_f^t``; the
:mod:`comprehension` module realises ``Ext^t``, ``Ext^k``,
``{p:-}_t``, ``{p:-}_⊤``; ``index_map`` realises Beck-Chevalley
through cellwise pullback squares.

This module collects them into one aggregate :class:`PredicationHyperdoctrine`
so calling code talks to the *hyperdoctrine* rather than threading the
right morphism instance into each call. It does no new math — every
method delegates to the existing primitive — but it gives the calculator
a single coherent object whose API mirrors the corpus statement of
predication-hyperdoctrine.

Realises corpus object ``predication-hyperdoctrine``. The underlying
predication fibration exposes the corpus ``predication-fiber-functor``
as :class:`pypredcalc.predication.fibration.PredicationFiberFunctor`.
"""

