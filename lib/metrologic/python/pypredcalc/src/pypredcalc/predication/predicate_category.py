"""Predicate category: a small category whose objects are predicates.

Realizes corpus objects:

- ``predicate-set`` — :class:`PredicateSet`, the finite ordered carrier
  ``Π = Ob(𝒞)``.
- ``predication-cell-set`` — :class:`PredicationCellSet`, the Cartesian
  product ``Φ = E × Π × E``.
- ``predicate-category`` — :class:`PredicateCategory`, a small category
  on a finite predicate set generated by the four canonical morphism
  classes.

Realizes corpus morphisms:

- ``predicate-specialization`` — :class:`PredicateSpecialization`.
- ``predicate-converse`` — :class:`PredicateConverse`.
- ``predicate-subject-projection`` — :class:`PredicateSubjectProjection`.
- ``predicate-object-projection`` — :class:`PredicateObjectProjection`.

Each predicate morphism induces a pullback ``f^* : A_p → A_q`` that acts
pointwise on :class:`FiberValuation` instances — see
:meth:`PredicateMorphism.pullback`. The fiber valuation type is the full
predication-fiber-algebra ``A_p = L^{⋈ E×E}`` over an arbitrary residuated
lattice ``L``, defined in :mod:`pypredcalc.predication.fiber_valuation`.
"""

