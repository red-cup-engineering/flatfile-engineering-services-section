@realizes("objects/predicate-category")
@dataclass(frozen=True)
class PredicateCategory:
    """A small category whose objects are predicates.

    A :class:`PredicateCategory` carries an entity set ``E``, a predicate
    set ``Π = Ob(𝒞)``, an optional per-predicate **domain** assignment
    ``dom : Π → 2^{E×E}`` (defaulting to the full ``E × E`` for any
    unspecified predicate), and a tuple of *generator* morphisms drawn
    from the four canonical classes. Identities and pullbacks of
    generators are derived; this class does not eagerly enumerate the
    full arrow set generated under composition (which can be large), but
    does provide composition (:meth:`compose`) and a :meth:`is_natural`
    check that verifies a candidate cross-fiber valuation respects every
    generator's pullback.

    Domain assignments matter most for **specialization**: the corpus
    defines ``f : q → p`` to carry a sub-support inclusion
    ``ι_f : dom(q) ↪ dom(p)``, so each :class:`PredicateSpecialization`
    generator is checked at construction time to satisfy
    ``sub_support == dom(q) ⊆ dom(p)``. Converse and projection
    generators are checked against their induced entity-pair maps too,
    so every generator's pullback lands in the declared source domain.
    :meth:`validate_valuation` uses ``dom`` to ensure each fiber's
    support lies inside its predicate's domain.
    """

    entities: EntitySet
    predicates: PredicateSet
    generators: tuple[PredicateMorphism, ...] = ()
    domains: Mapping[Hashable, frozenset[tuple[Hashable, Hashable]]] = field(
        default_factory=dict
    )

    def __post_init__(self) -> None:
        full_pairs = frozenset(
            (s, o) for s in self.entities for o in self.entities
        )
        # Canonicalise: build a defensive frozen-dict-of-frozensets, defaulting
        # missing predicates to the full E × E and validating supplied domains
        # are subsets of E × E.
        canonical: dict[Hashable, frozenset[tuple[Hashable, Hashable]]] = {}
        for predicate in self.predicates:
            raw = self.domains.get(predicate)
            if raw is None:
                canonical[predicate] = full_pairs
                continue
            dom = frozenset(raw)
            stray = [pair for pair in dom if pair not in full_pairs]
            if stray:
                raise ValueError(
                    f"domain for predicate {predicate!r} contains non-entity-pair "
                    f"cells: {stray!r}"
                )
            canonical[predicate] = dom
        # Reject any keys in `domains` that aren't predicates of the category.
        unknown = [k for k in self.domains if k not in self.predicates]
        if unknown:
            raise ValueError(
                f"domains given for predicates not in predicate set: {unknown!r}"
            )
        # Wrap in MappingProxyType so external code cannot mutate domain
        # invariants after construction.
        object.__setattr__(self, "domains", MappingProxyType(canonical))

        for morphism in self.generators:
            if not _is_canonical_generator(morphism):
                raise TypeError(
                    "predicate-category generators must be one of the four "
                    "canonical predication morphism classes: "
                    "PredicateSpecialization, PredicateConverse, "
                    "PredicateSubjectProjection, or PredicateObjectProjection"
                )
            if morphism.source not in self.predicates:
                raise ValueError(
                    f"morphism source {morphism.source!r} not in predicate set"
                )
            if morphism.target not in self.predicates:
                raise ValueError(
                    f"morphism target {morphism.target!r} not in predicate set"
                )
            dom_q = canonical[morphism.source]
            dom_p = canonical[morphism.target]
            if isinstance(morphism, PredicateSpecialization):
                bad = [pair for pair in morphism.sub_support if pair not in full_pairs]
                if bad:
                    raise ValueError(
                        f"specialization sub-support contains non-entity-pair "
                        f"cells: {bad!r}"
                    )
                if morphism.sub_support != dom_q:
                    raise ValueError(
                        f"specialization {morphism.source!r} -> {morphism.target!r}: "
                        f"sub_support must equal dom(source); got "
                        f"{set(morphism.sub_support)!r} vs dom={set(dom_q)!r}"
                    )
                if not dom_q <= dom_p:
                    extra = dom_q - dom_p
                    raise ValueError(
                        f"specialization {morphism.source!r} -> {morphism.target!r}: "
                        f"dom(source) ⊄ dom(target); cells in source-domain not in "
                        f"target-domain: {set(extra)!r}"
                    )
            elif isinstance(morphism, PredicateConverse):
                expected = _swap_dom(dom_p)
                if dom_q != expected:
                    raise ValueError(
                        f"converse {morphism.source!r} -> {morphism.target!r}: "
                        f"dom(source) must equal swap(dom(target)); got "
                        f"{set(dom_q)!r} vs expected {set(expected)!r}"
                    )
            elif isinstance(morphism, PredicateSubjectProjection):
                expected = _subject_projection_dom(dom_p, self.entities)
                if dom_q != expected:
                    raise ValueError(
                        f"subject-projection {morphism.source!r} -> "
                        f"{morphism.target!r}: dom(source) must equal the "
                        f"subject-diagonal broadcast of dom(target); got "
                        f"{set(dom_q)!r} vs expected {set(expected)!r}"
                    )
            elif isinstance(morphism, PredicateObjectProjection):
                expected = _object_projection_dom(dom_p, self.entities)
                if dom_q != expected:
                    raise ValueError(
                        f"object-projection {morphism.source!r} -> "
                        f"{morphism.target!r}: dom(source) must equal the "
                        f"object-diagonal broadcast of dom(target); got "
                        f"{set(dom_q)!r} vs expected {set(expected)!r}"
                    )

    def objects(self) -> PredicateSet:
        """Return the object set ``Π = Ob(𝒞)``."""
        return self.predicates

    def cell_set(self) -> PredicationCellSet:
        """Return the predication cell set ``Φ = E × Π × E``."""
        return PredicationCellSet(self.entities, self.predicates)

    def dom_of(self, predicate: Hashable) -> frozenset[tuple[Hashable, Hashable]]:
        """Return the designated domain ``dom(predicate) ⊆ E × E``.

        Predicates without an explicit domain default to the full
        ``E × E``.
        """
        if predicate not in self.predicates:
            raise KeyError(f"{predicate!r} not in predicate set")
        return self.domains[predicate]

    def validate_valuation(
        self, valuation: Mapping[Hashable, FiberValuation[T]]
    ) -> None:
        """Raise ``ValueError`` if any fiber's support escapes its predicate domain.

        A cross-fiber valuation ``v : Π → ⋃_p A_p`` is *domain-respecting*
        when ``support(v(p)) ⊆ dom(p)`` for every predicate. The corpus
        treats out-of-domain cells as undefined / structurally absent; this
        helper makes the invariant explicit.
        """
        for predicate in self.predicates:
            if predicate not in valuation:
                raise KeyError(
                    f"valuation missing fiber for predicate {predicate!r}"
                )
            dom = self.domains[predicate]
            stray = valuation[predicate].support() - dom
            if stray:
                raise ValueError(
                    f"valuation at predicate {predicate!r} has support outside "
                    f"dom: {set(stray)!r}"
                )

    def identity(self, predicate: Hashable) -> PredicateIdentity:
        """Return the identity morphism ``id_p`` on ``p``."""
        if predicate not in self.predicates:
            raise KeyError(f"{predicate!r} not in predicate set")
        return PredicateIdentity(source=predicate, target=predicate)

    def contains_morphism(self, morphism: PredicateMorphism) -> bool:
        """Return whether ``morphism`` is an arrow of this predicate category."""
        if morphism.source not in self.predicates:
            return False
        if morphism.target not in self.predicates:
            return False
        if isinstance(morphism, PredicateIdentity):
            return morphism.source == morphism.target
        if morphism in self.generators:
            return True
        if isinstance(morphism, _ComposedMorphism):
            return self.contains_morphism(
                morphism._first
            ) and self.contains_morphism(morphism._second)
        return False

    def compose(
        self, g: PredicateMorphism, f: PredicateMorphism
    ) -> _ComposedMorphism | PredicateMorphism:
        """Compose ``g ∘ f``, requiring ``f.target == g.source``.

        Identities collapse: ``id ∘ f = f`` and ``g ∘ id = g``. Otherwise
        the result is a :class:`_ComposedMorphism` whose pullback is the
        composition ``f^* ∘ g^*`` (in that order — pullback is
        contravariant).
        """
        if not self.contains_morphism(f):
            raise KeyError(f"{f!r} is not a morphism of this predicate category")
        if not self.contains_morphism(g):
            raise KeyError(f"{g!r} is not a morphism of this predicate category")
        if f.target != g.source:
            raise ValueError(
                f"cannot compose: f.target={f.target!r} ≠ g.source={g.source!r}"
            )
        if f.is_identity():
            return g
        if g.is_identity():
            return f
        return _ComposedMorphism(
            source=f.source,
            target=g.target,
            _first=f,
            _second=g,
            _middle_dom=self.dom_of(f.target),
        )

    def generated_morphisms(
        self,
        *,
        max_depth: int = 1,
    ) -> tuple[PredicateMorphism, ...]:
        """Enumerate identities, generators, and composites up to ``max_depth``.

        Depth counts non-identity generator factors. ``max_depth=1`` returns
        identities and declared generators; larger values close under
        composition up to the requested generator length.
        """
        if max_depth < 0:
            raise ValueError("max_depth must be non-negative")
        arrows: list[PredicateMorphism] = [
            self.identity(predicate) for predicate in self.predicates
        ]
        if max_depth == 0:
            return tuple(arrows)
        arrows.extend(self.generators)
        frontier: list[PredicateMorphism] = list(self.generators)
        for _depth in range(2, max_depth + 1):
            next_frontier: list[PredicateMorphism] = []
            for f in frontier:
                for g in self.generators:
                    if f.target != g.source:
                        continue
                    composite = self.compose(g, f)
                    if composite not in arrows:
                        arrows.append(composite)
                    if composite not in next_frontier:
                        next_frontier.append(composite)
            frontier = next_frontier
            if not frontier:
                break
        return tuple(arrows)

    @realizes("theorems/predicate-generator-pullback-closure")
    def generator_pullback_closure(
        self,
        f: PredicateMorphism,
        g: PredicateMorphism,
        *,
        pullback_object: Hashable | None = None,
    ) -> PredicateGeneratorPullbackClosureWitness:
        """Return the PredCat pullback-closure witness for ``f`` and ``g``.

        ``f`` and ``g`` must be identity arrows or canonical generator arrows
        with a shared target. The returned square is represented again by a
        predicate object whose domain is a sub-support of ``E × E`` and by
        projection arrows drawn from the same PredCat generator inventory.
        """
        if not self.contains_morphism(f):
            raise KeyError(f"{f!r} is not a morphism of this predicate category")
        if not self.contains_morphism(g):
            raise KeyError(f"{g!r} is not a morphism of this predicate category")
        if f.target != g.target:
            raise ValueError("generator pullback closure requires shared target")
        if not _is_predcat_generator_or_identity(f):
            raise TypeError(f"{f!r} is not a PredCat generator or identity")
        if not _is_predcat_generator_or_identity(g):
            raise TypeError(f"{g!r} is not a PredCat generator or identity")

        target_dom = self.dom_of(f.target)
        f_dom = self.dom_of(f.source)
        g_dom = self.dom_of(g.source)
        pb_object = (
            pullback_object
            if pullback_object is not None
            else ("pullback", f.source, g.source, f.target)
        )
        p_a: PredicateMorphism
        p_b: PredicateMorphism
        pb_dom: frozenset[tuple[Hashable, Hashable]]

        if isinstance(f, PredicateIdentity):
            pb_object = g.source
            pb_dom = g_dom
            p_a = g
            p_b = PredicateIdentity(source=g.source, target=g.source)
            case = f"identity/{_morphism_kind(g)}"
        elif isinstance(g, PredicateIdentity):
            pb_object = f.source
            pb_dom = f_dom
            p_a = PredicateIdentity(source=f.source, target=f.source)
            p_b = f
            case = f"{_morphism_kind(f)}/identity"
        else:
            pb_dom, p_a, p_b, case = _generator_pullback_case(
                f=f,
                g=g,
                f_dom=f_dom,
                g_dom=g_dom,
                target_dom=target_dom,
                entities=self.entities,
                pullback_object=pb_object,
            )

        left, right = _compose_cell_maps(
            f=f,
            g=g,
            p_a=p_a,
            p_b=p_b,
            pullback_domain=pb_dom,
            f_source_domain=f_dom,
            g_source_domain=g_dom,
            target_domain=target_dom,
            entities=self.entities,
        )
        return PredicateGeneratorPullbackClosureWitness(
            f=f,
            g=g,
            pullback_object=pb_object,
            pullback_domain=pb_dom,
            p_a=p_a,
            p_b=p_b,
            target_domain=target_dom,
            f_source_domain=f_dom,
            g_source_domain=g_dom,
            case=case,
            left_composite=MappingProxyType(left),
            right_composite=MappingProxyType(right),
        )

    @realizes("concepts/predicate-category-naturality")
    def naturality(
        self, valuation: Mapping[Hashable, FiberValuation[T]]
    ) -> NaturalityWitness[T]:
        """Return the structural naturality witness for a cross-fiber valuation.

        A valuation ``v : Π → ⋃_p A_p`` (one fiber valuation per
        predicate) is **𝒞-natural** iff for every generator
        ``f : q → p``, ``f^*(v(p)) = v(q)``. This method computes that
        check at every generator and returns a :class:`NaturalityWitness`
        recording per-generator results. Read ``witness.holds`` for the
        flat answer, ``witness.failures`` to localise failure, or use the
        witness in a boolean context (``if witness:``).

        See `concepts/predicate-category-naturality.md` in the corpus.
        """
        from .witness import GeneratorNaturalityCheck, NaturalityWitness

        for predicate in self.predicates:
            if predicate not in valuation:
                raise KeyError(
                    f"valuation missing fiber for predicate {predicate!r}"
                )
        checks: list[GeneratorNaturalityCheck[T]] = []
        for morphism in self.generators:
            pulled = morphism.pullback(valuation[morphism.target])
            expected = valuation[morphism.source]
            checks.append(
                GeneratorNaturalityCheck(
                    generator=morphism, pulled=pulled, expected=expected
                )
            )
        return NaturalityWitness(valuation=valuation, checks=tuple(checks))

    def is_natural(
        self, valuation: Mapping[Hashable, FiberValuation[T]]
    ) -> bool:
        """Return ``bool(self.naturality(valuation))``.

        Thin convenience for callers who only want the flat answer.
        Prefer :meth:`naturality` when you can use the witness — it
        carries the per-generator structure that the bool throws away.
        """
        return bool(self.naturality(valuation))

    def __repr__(self) -> str:
        return (
            f"PredicateCategory(entities={self.entities!r}, "
            f"predicates={self.predicates!r}, "
            f"generators=<{len(self.generators)} morphisms>)"
                )


def _is_canonical_generator(morphism: PredicateMorphism) -> bool:
    return isinstance(
        morphism,
        (
            PredicateSpecialization,
            PredicateConverse,
            PredicateSubjectProjection,
            PredicateObjectProjection,
        ),
    )


def _is_predcat_generator_or_identity(morphism: PredicateMorphism) -> bool:
    return isinstance(morphism, PredicateIdentity) or _is_canonical_generator(
        morphism
    )


def _morphism_kind(morphism: PredicateMorphism) -> str:
    if isinstance(morphism, PredicateIdentity):
        return "identity"
    if isinstance(morphism, PredicateSpecialization):
        return "specialization"
    if isinstance(morphism, PredicateConverse):
        return "converse"
    if isinstance(morphism, PredicateSubjectProjection):
        return "subject_projection"
    if isinstance(morphism, PredicateObjectProjection):
        return "object_projection"
    raise TypeError(f"not a canonical PredCat generator: {morphism!r}")


def _generator_pullback_case(
    *,
    f: PredicateMorphism,
    g: PredicateMorphism,
    f_dom: frozenset[tuple[Hashable, Hashable]],
    g_dom: frozenset[tuple[Hashable, Hashable]],
    target_dom: frozenset[tuple[Hashable, Hashable]],
    entities: EntitySet,
    pullback_object: Hashable,
) -> tuple[
    frozenset[tuple[Hashable, Hashable]],
    PredicateMorphism,
    PredicateMorphism,
    str,
]:
    f_kind = _morphism_kind(f)
    g_kind = _morphism_kind(g)
    case = f"{f_kind}/{g_kind}"

    if f_kind == "specialization" and g_kind == "specialization":
        pb_dom = f_dom & g_dom
        p_a_kind = "specialization"
        p_b_kind = "specialization"
    elif f_kind == "specialization" and g_kind == "converse":
        pb_dom = _swap_dom(f_dom)
        p_a_kind = "converse"
        p_b_kind = "specialization"
    elif f_kind == "converse" and g_kind == "specialization":
        pb_dom = _swap_dom(g_dom)
        p_a_kind = "specialization"
        p_b_kind = "converse"
    elif f_kind == "specialization" and g_kind == "subject_projection":
        pb_dom = _subject_projection_dom(f_dom, entities)
        p_a_kind = "subject_projection"
        p_b_kind = "specialization"
    elif f_kind == "subject_projection" and g_kind == "specialization":
        pb_dom = _subject_projection_dom(g_dom, entities)
        p_a_kind = "specialization"
        p_b_kind = "subject_projection"
    elif f_kind == "specialization" and g_kind == "object_projection":
        pb_dom = _object_projection_dom(f_dom, entities)
        p_a_kind = "object_projection"
        p_b_kind = "specialization"
    elif f_kind == "object_projection" and g_kind == "specialization":
        pb_dom = _object_projection_dom(g_dom, entities)
        p_a_kind = "specialization"
        p_b_kind = "object_projection"
    elif f_kind == "converse" and g_kind == "converse":
        pb_dom = f_dom & g_dom
        p_a_kind = "specialization"
        p_b_kind = "specialization"
    elif (
        f_kind in {"converse", "subject_projection", "object_projection"}
        and g_kind in {"converse", "subject_projection", "object_projection"}
    ):
        if f_kind == g_kind:
            pb_dom = f_dom & g_dom
        else:
            pb_dom = _diagonal_dom(target_dom)
        p_a_kind = "specialization"
        p_b_kind = "specialization"
    else:  # pragma: no cover - exhaustive over canonical non-identity kinds.
        raise TypeError(f"unhandled generator pullback case {case!r}")

    p_a = _projection_for_kind(
        kind=p_a_kind,
        source=pullback_object,
        target=f.source,
        source_dom=pb_dom,
        target_dom=f_dom,
        entities=entities,
    )
    p_b = _projection_for_kind(
        kind=p_b_kind,
        source=pullback_object,
        target=g.source,
        source_dom=pb_dom,
        target_dom=g_dom,
        entities=entities,
    )
    return pb_dom, p_a, p_b, case


def _projection_for_kind(
    *,
    kind: str,
    source: Hashable,
    target: Hashable,
    source_dom: frozenset[tuple[Hashable, Hashable]],
    target_dom: frozenset[tuple[Hashable, Hashable]],
    entities: EntitySet,
) -> PredicateMorphism:
    if kind == "specialization":
        if not source_dom <= target_dom:
            raise ValueError(
                "specialization projection requires source_dom ⊆ target_dom"
            )
        return PredicateSpecialization(
            source=source,
            target=target,
            sub_support=source_dom,
        )
    if kind == "converse":
        if source_dom != _swap_dom(target_dom):
            raise ValueError(
                "converse projection requires source_dom == swap(target_dom)"
            )
        return PredicateConverse(source=source, target=target)
    if kind == "subject_projection":
        if source_dom != _subject_projection_dom(target_dom, entities):
            raise ValueError(
                "subject projection requires the subject broadcast domain"
            )
        return PredicateSubjectProjection(source=source, target=target)
    if kind == "object_projection":
        if source_dom != _object_projection_dom(target_dom, entities):
            raise ValueError(
                "object projection requires the object broadcast domain"
            )
        return PredicateObjectProjection(source=source, target=target)
    raise ValueError(f"unknown projection kind {kind!r}")


def _compose_cell_maps(
    *,
    f: PredicateMorphism,
    g: PredicateMorphism,
    p_a: PredicateMorphism,
    p_b: PredicateMorphism,
    pullback_domain: frozenset[tuple[Hashable, Hashable]],
    f_source_domain: frozenset[tuple[Hashable, Hashable]],
    g_source_domain: frozenset[tuple[Hashable, Hashable]],
    target_domain: frozenset[tuple[Hashable, Hashable]],
    entities: EntitySet,
) -> tuple[
    dict[tuple[Hashable, Hashable], tuple[Hashable, Hashable]],
    dict[tuple[Hashable, Hashable], tuple[Hashable, Hashable]],
]:
    p_a_map = _cell_map_for(
        p_a,
        source_dom=pullback_domain,
        target_dom=f_source_domain,
        entities=entities,
    )
    p_b_map = _cell_map_for(
        p_b,
        source_dom=pullback_domain,
        target_dom=g_source_domain,
        entities=entities,
    )
    f_map = _cell_map_for(
        f,
        source_dom=f_source_domain,
        target_dom=target_domain,
        entities=entities,
    )
    g_map = _cell_map_for(
        g,
        source_dom=g_source_domain,
        target_dom=target_domain,
        entities=entities,
    )
    left = {cell: f_map[p_a_map[cell]] for cell in pullback_domain}
    right = {cell: g_map[p_b_map[cell]] for cell in pullback_domain}
    return left, right


def _cell_map_for(
    morphism: PredicateMorphism,
    *,
    source_dom: frozenset[tuple[Hashable, Hashable]],
    target_dom: frozenset[tuple[Hashable, Hashable]],
    entities: EntitySet,
) -> dict[tuple[Hashable, Hashable], tuple[Hashable, Hashable]]:
    if isinstance(morphism, (PredicateIdentity, PredicateSpecialization)):
        mapping = {cell: cell for cell in source_dom}
    elif isinstance(morphism, PredicateConverse):
        mapping = {(s, o): (o, s) for (s, o) in source_dom}
    elif isinstance(morphism, PredicateSubjectProjection):
        mapping = {(s, o): (s, s) for (s, o) in source_dom}
    elif isinstance(morphism, PredicateObjectProjection):
        mapping = {(s, o): (o, o) for (s, o) in source_dom}
    else:
        raise TypeError(f"not a canonical PredCat generator: {morphism!r}")

    stray = [image for image in mapping.values() if image not in target_dom]
    if stray:
        raise ValueError(
            f"{type(morphism).__name__} maps outside target domain: {stray!r}"
        )
    if isinstance(morphism, PredicateIdentity) and source_dom != target_dom:
        raise ValueError("identity cell map requires source_dom == target_dom")
    if isinstance(morphism, PredicateSubjectProjection):
        expected = _subject_projection_dom(target_dom, entities)
        if source_dom != expected:
            raise ValueError(
                "subject-projection cell map requires source_dom to be the "
                "subject broadcast of target_dom"
            )
    if isinstance(morphism, PredicateObjectProjection):
        expected = _object_projection_dom(target_dom, entities)
        if source_dom != expected:
            raise ValueError(
                "object-projection cell map requires source_dom to be the "
                "object broadcast of target_dom"
            )
    if isinstance(morphism, PredicateConverse) and source_dom != _swap_dom(target_dom):
        raise ValueError("converse cell map requires source_dom == swap(target_dom)")
    if isinstance(morphism, PredicateSpecialization) and source_dom != morphism.sub_support:
        raise ValueError(
            "specialization cell map requires source_dom == sub_support"
        )
    return mapping


def _swap_dom(
    dom: frozenset[tuple[Hashable, Hashable]],
) -> frozenset[tuple[Hashable, Hashable]]:
    return frozenset((o, s) for s, o in dom)


def _diagonal_dom(
    dom: frozenset[tuple[Hashable, Hashable]],
) -> frozenset[tuple[Hashable, Hashable]]:
    return frozenset((s, o) for s, o in dom if s == o)


def _subject_projection_dom(
    target_dom: frozenset[tuple[Hashable, Hashable]],
    entities: EntitySet,
) -> frozenset[tuple[Hashable, Hashable]]:
    subjects = {s for s in entities if (s, s) in target_dom}
    return frozenset((s, o) for s in subjects for o in entities)


def _object_projection_dom(
    target_dom: frozenset[tuple[Hashable, Hashable]],
    entities: EntitySet,
) -> frozenset[tuple[Hashable, Hashable]]:
    objects = {o for o in entities if (o, o) in target_dom}
    return frozenset((s, o) for s in entities for o in objects)


@dataclass(frozen=True)
class _ComposedMorphism(PredicateMorphism):
    """Result of :meth:`PredicateCategory.compose` on two non-identity arrows.

    The pullback acts as ``f^* ∘ g^*`` — pullback is contravariant in
    composition.
    """

    _first: PredicateMorphism
    _second: PredicateMorphism
    _middle_dom: frozenset[tuple[Hashable, Hashable]]

    def pullback(self, fiber: FiberValuation[T]) -> FiberValuation[T]:
        intermediate = self._second.pullback(fiber)
        return self._first.pullback(intermediate)

    def existential_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        intermediate = self._first.existential_k(fiber, self._middle_dom)
        return self._second.existential_k(intermediate, target_dom)

    def existential_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        intermediate = self._first.existential_t(fiber, self._middle_dom)
        return self._second.existential_t(intermediate, target_dom)

    def universal_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        intermediate = self._first.universal_k(fiber, self._middle_dom)
        return self._second.universal_k(intermediate, target_dom)

    def universal_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        intermediate = self._first.universal_t(fiber, self._middle_dom)
        return self._second.universal_t(intermediate, target_dom)


def _project_along_diagonal(
    fiber: FiberValuation[T],
    target_dom: frozenset[tuple[Hashable, Hashable]],
    *,
    op: str,
    axis: str,
    order: str,
) -> FiberValuation[T]:
    """Compute the ``∃`` / ``∀`` adjoint for a projection morphism in a
    chosen order.

    ``axis="subject"`` means index map ``(s, o) ↦ (s, s)``;
    ``axis="object"`` means ``(s, o) ↦ (o, o)``.
    ``order`` is ``"k"`` (knowledge) or ``"t"`` (truth) and selects the
    join/meet, the empty-join value (``⊥_*``), and the empty-meet
    value (``⊤_*``).

    For each diagonal cell ``(d, d) ∈ target_dom`` we collect the
    pre-image — the row (subject axis) or column (object axis) of
    ``dom(q)`` whose projection lands at ``(d, d)`` — and reduce by the
    selected join (``∃``) or meet (``∀``). Off-diagonal cells in
    ``target_dom`` get the appropriate ``⊥`` (``∃``: empty join) or ``⊤``
    (``∀``: empty meet) for that order.
    """
    bil = fiber.bilattice
    bottom = fiber.bottom
    if order == "k":
        if op == "existential":
            reduce_op = bil.knowledge_join
            empty_value = bil.knowledge_bottom()
        elif op == "universal":
            reduce_op = bil.knowledge_meet
            empty_value = bil.knowledge_top()
        else:
            raise ValueError(f"unknown op {op!r}")
    elif order == "t":
        if op == "existential":
            reduce_op = bil.truth_join
            empty_value = bil.truth_bottom()
        elif op == "universal":
            reduce_op = bil.truth_meet
            empty_value = bil.truth_top()
        else:
            raise ValueError(f"unknown op {op!r}")
    else:
        raise ValueError(f"unknown order {order!r}; expected 'k' or 't'")

    # Group input cells by their projection-image.
    by_image: dict[Hashable, list[tuple[Hashable, Hashable]]] = {}
    for s, o in fiber.dom:
        image = s if axis == "subject" else o
        by_image.setdefault(image, []).append((s, o))

    cells: dict[tuple[Hashable, Hashable], tuple[T, T]] = {}
    for cell in target_dom:
        s_prime, o_prime = cell
        if s_prime != o_prime:
            value = empty_value
        else:
            d = s_prime
            preimage = by_image.get(d, [])
            if not preimage:
                value = empty_value
            else:
                values = [fiber.get(*pair) for pair in preimage]
                value = values[0]
                for v in values[1:]:
                    value = reduce_op(value, v)
        if value != bottom:
            cells[cell] = value

    return FiberValuation(
        bilattice=bil,
        entities=fiber.entities,
        bottom=bottom,
        cells=cells,
        dom=target_dom,
    )
