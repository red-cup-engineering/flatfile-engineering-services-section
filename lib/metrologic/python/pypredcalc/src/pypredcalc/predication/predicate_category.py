@realizes("objects/predicate-set")
@dataclass(frozen=True)
class PredicateSet:
    """Finite ordered set of predicate identifiers — ``Π = Ob(𝒞)``.

    Stored as a tuple to lock element order; the constructor de-duplicates
    while preserving first-occurrence order via :meth:`of`.
    """

    predicates: tuple[Hashable, ...]

    @classmethod
    def of(cls, items: Iterable[Hashable]) -> PredicateSet:
        seen: set[Hashable] = set()
        out: list[Hashable] = []
        for x in items:
            if x in seen:
                continue
            seen.add(x)
            out.append(x)
        return cls(tuple(out))

    def __post_init__(self) -> None:
        if len(set(self.predicates)) != len(self.predicates):
            raise ValueError("PredicateSet predicates must be unique")

    def __len__(self) -> int:
        return len(self.predicates)

    def __contains__(self, item: object) -> bool:
        return item in self.predicates

    def __iter__(self) -> Iterator[Hashable]:
        return iter(self.predicates)

    def index(self, item: Hashable) -> int:
        try:
            return self.predicates.index(item)
        except ValueError as exc:
            raise KeyError(f"{item!r} not in PredicateSet") from exc

    def union(self, other: PredicateSet) -> PredicateSet:
        return PredicateSet.of(list(self.predicates) + list(other.predicates))

    def intersection(self, other: PredicateSet) -> PredicateSet:
        other_set = set(other.predicates)
        return PredicateSet(tuple(x for x in self.predicates if x in other_set))

    def __repr__(self) -> str:
        return f"PredicateSet({list(self.predicates)!r})"


@dataclass(frozen=True)
class PredicationCellSet:
    """The Cartesian product ``Φ = E × Π × E`` of a predicate category.

    Iteration yields ``(subject, predicate, object)`` triples in
    lexicographic order: outer loop subjects (in entity-set order), middle
    loop predicates (in predicate-set order), inner loop objects (in
    entity-set order).
    """

    entities: EntitySet
    predicates: PredicateSet

    def __len__(self) -> int:
        n = len(self.entities)
        return n * len(self.predicates) * n

    def __iter__(self) -> Iterator[tuple[Hashable, Hashable, Hashable]]:
        for subject in self.entities:
            for predicate in self.predicates:
                for object_ in self.entities:
                    yield (subject, predicate, object_)

    def __contains__(self, item: object) -> bool:
        if not (isinstance(item, tuple) and len(item) == 3):
            return False
        subject, predicate, object_ = item
        return (
            subject in self.entities
            and predicate in self.predicates
            and object_ in self.entities
        )

    def __repr__(self) -> str:
        return (
            f"PredicationCellSet(entities={self.entities!r}, "
            f"predicates={self.predicates!r})"
        )


