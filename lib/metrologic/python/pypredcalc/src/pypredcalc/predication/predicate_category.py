@dataclass(frozen=True)
class PredicateMorphism:
    """Abstract base for the four canonical predicate-morphism classes.

    A predicate morphism ``f : source -> target`` carries:

    - the **pullback** ``f^* : A_target -> A_source`` — :meth:`pullback`;
    - the four **adjoints** along ``f``: ``∃_f^k``, ``∃_f^t`` (left
      adjoints to ``f^*`` in the knowledge / truth orders) and
      ``∀_f^k``, ``∀_f^t`` (right adjoints) — :meth:`existential_k`,
      :meth:`existential_t`, :meth:`universal_k`, :meth:`universal_t`.

    The corpus theorem ``predication-bilattice-fibration-axioms``
    requires every predicate morphism to support all five operations;
    the four canonical generator classes (identity, specialization,
    converse, projection) override each of them.
    """

    source: Hashable
    target: Hashable

    def pullback(self, fiber: FiberValuation[T]) -> FiberValuation[T]:
        """Apply the pullback ``f^* : A_target → A_source`` at the
        fiber-algebra level. The :class:`FiberValuation` carries its own
        ``entities``, ``bilattice``, and ``bottom``, so this method needs
        no extra arguments. Concrete subclasses override.
        """
        raise NotImplementedError  # pragma: no cover — abstract

    def existential_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∃_f^k : A_source → A_target`` — left adjoint to ``f^*`` in ``≤_k``."""
        raise NotImplementedError  # pragma: no cover — abstract

    def existential_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∃_f^t : A_source → A_target`` — left adjoint to ``f^*`` in ``≤_t``."""
        raise NotImplementedError  # pragma: no cover — abstract

    def universal_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∀_f^k : A_source → A_target`` — right adjoint to ``f^*`` in ``≤_k``."""
        raise NotImplementedError  # pragma: no cover — abstract

    def universal_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∀_f^t : A_source → A_target`` — right adjoint to ``f^*`` in ``≤_t``."""
        raise NotImplementedError  # pragma: no cover — abstract

    def is_identity(self) -> bool:
        return False


@realizes("theorems/predicate-generator-pullback-closure")
@dataclass(frozen=True)
class PredicateGeneratorPullbackClosureWitness:
    """A PredCat pullback-closure witness for two generator arrows.

    The corpus theorem is not the generic set-theoretic pullback of two
    arbitrary cell maps. It says the four predicate-category generator
    classes are closed under pullback formation inside ``𝒞``. This witness
    records the pullback object's entity-pair support and the two projection
    arrows as predicate morphisms, then checks the induced cell maps commute.
    """

    f: PredicateMorphism
    g: PredicateMorphism
    pullback_object: Hashable
    pullback_domain: frozenset[tuple[Hashable, Hashable]]
    p_a: PredicateMorphism
    p_b: PredicateMorphism
    target_domain: frozenset[tuple[Hashable, Hashable]]
    f_source_domain: frozenset[tuple[Hashable, Hashable]]
    g_source_domain: frozenset[tuple[Hashable, Hashable]]
    case: str
    left_composite: Mapping[
        tuple[Hashable, Hashable], tuple[Hashable, Hashable]
    ]
    right_composite: Mapping[
        tuple[Hashable, Hashable], tuple[Hashable, Hashable]
    ]

    @property
    def commutes(self) -> bool:
        return dict(self.left_composite) == dict(self.right_composite)

    @property
    def projections_are_predcat_generators(self) -> bool:
        return _is_predcat_generator_or_identity(
            self.p_a
        ) and _is_predcat_generator_or_identity(self.p_b)

    @property
    def holds(self) -> bool:
        return (
            self.f.target == self.g.target
            and self.p_a.source == self.pullback_object
            and self.p_a.target == self.f.source
            and self.p_b.source == self.pullback_object
            and self.p_b.target == self.g.source
            and self.projections_are_predcat_generators
            and self.commutes
        )

    def __bool__(self) -> bool:
        return self.holds


@dataclass(frozen=True)
class PredicateIdentity(PredicateMorphism):
    """The identity morphism ``id_p : p -> p``.

    The pullback acts as the identity on fiber valuations.
    """

    def __post_init__(self) -> None:
        if self.source != self.target:
            raise ValueError("PredicateIdentity requires source == target")

    def pullback(self, fiber: FiberValuation[T]) -> FiberValuation[T]:
        return fiber

    def existential_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∃_id^k = id``. Requires ``target_dom == fiber.dom``."""
        return self._identity_adjoint(fiber, target_dom)

    def universal_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∀_id^k = id``. Requires ``target_dom == fiber.dom``."""
        return self._identity_adjoint(fiber, target_dom)

    def existential_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∃_id^t = id``."""
        return self._identity_adjoint(fiber, target_dom)

    def universal_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∀_id^t = id``."""
        return self._identity_adjoint(fiber, target_dom)

    def _identity_adjoint(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        if target_dom != fiber.dom:
            raise ValueError(
                "identity adjoints require target_dom == fiber.dom"
            )
        return fiber

    def is_identity(self) -> bool:
        return True


@realizes("morphisms/predicate-specialization")
@dataclass(frozen=True)
class PredicateSpecialization(PredicateMorphism):
    """Specialization ``f : q -> p`` along a sub-support ``ι : dom(q) ⊆ dom(p)``.

    The pullback restricts a fiber valuation on ``p`` to the sub-support;
    the output fiber's ``dom`` is exactly ``sub_support``::

        (f^* v) ∈ A_q = L^{⋈ sub_support}, with (f^* v)(s, o) = v(s, o).
    """

    sub_support: frozenset[tuple[Hashable, Hashable]]

    def pullback(self, fiber: FiberValuation[T]) -> FiberValuation[T]:
        if not self.sub_support <= fiber.dom:
            raise ValueError(
                f"specialization sub_support is not a subset of the input "
                f"fiber's dom; missing cells: "
                f"{set(self.sub_support) - set(fiber.dom)!r}"
            )
        cells: dict[tuple[Hashable, Hashable], tuple[T, T]] = {
            pair: fiber.get(*pair)
            for pair in self.sub_support
            if fiber.get(*pair) != fiber.bottom
        }
        return FiberValuation(
            bilattice=fiber.bilattice,
            entities=fiber.entities,
            bottom=fiber.bottom,
            cells=cells,
            dom=self.sub_support,
        )

    def existential_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """Left adjoint ``∃_f^k``: extends ``α`` from ``sub_support`` to
        ``target_dom`` by ``⊥_k``.

        Adjunction ``∃_f^k(α) ≤_k β ⇔ α ≤_k f^*(β)`` holds because
        ``⊥_k`` is the ``≤_k``-bottom (vacuously below outside-cells).
        """
        return self._extend_by(
            fiber, target_dom, off_value=fiber.bilattice.knowledge_bottom()
        )

    def universal_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """Right adjoint ``∀_f^k``: extends ``α`` by ``⊤_k``.

        Adjunction ``f^*(β) ≤_k α ⇔ β ≤_k ∀_f^k(α)`` holds because
        ``⊤_k`` is the ``≤_k``-top.
        """
        return self._extend_by(
            fiber, target_dom, off_value=fiber.bilattice.knowledge_top()
        )

    def existential_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """Left adjoint ``∃_f^t``: extends ``α`` by ``⊥_t = f``.

        Adjunction in the truth order: ``∃_f^t(α) ≤_t β ⇔ α ≤_t f^*(β)``.
        """
        return self._extend_by(
            fiber, target_dom, off_value=fiber.bilattice.truth_bottom()
        )

    def universal_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """Right adjoint ``∀_f^t``: extends ``α`` by ``⊤_t = t``."""
        return self._extend_by(
            fiber, target_dom, off_value=fiber.bilattice.truth_top()
        )

    def _extend_by(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
        *,
        off_value: tuple[T, T],
    ) -> FiberValuation[T]:
        """Common implementation: extend ``α`` from sub_support to
        target_dom by ``off_value`` outside sub_support."""
        self._require_input_on_sub_support(fiber)
        self._require_sub_support_in_target(target_dom)
        cells: dict[tuple[Hashable, Hashable], tuple[T, T]] = {}
        for pair in target_dom:
            if pair in self.sub_support:
                value = fiber.get(*pair)
            else:
                value = off_value
            if value != fiber.bottom:
                cells[pair] = value
        return FiberValuation(
            bilattice=fiber.bilattice,
            entities=fiber.entities,
            bottom=fiber.bottom,
            cells=cells,
            dom=target_dom,
        )

    def _require_input_on_sub_support(self, fiber: FiberValuation[T]) -> None:
        if fiber.dom != self.sub_support:
            raise ValueError(
                "specialization adjoints require input fiber over dom(q) = "
                "sub_support; got fiber with dom != sub_support"
            )

    def _require_sub_support_in_target(
        self, target_dom: frozenset[tuple[Hashable, Hashable]]
    ) -> None:
        if not self.sub_support <= target_dom:
            raise ValueError(
                f"target_dom must contain sub_support; missing cells: "
                f"{set(self.sub_support) - set(target_dom)!r}"
            )


@realizes("morphisms/predicate-converse")
@dataclass(frozen=True)
class PredicateConverse(PredicateMorphism):
    """Converse ``f : p^c -> p`` induced by the swap ``(s, o) ↦ (o, s)``.

    The pullback acts by ``(f^* v)(s, o) = v(o, s)`` on the swapped
    domain ``swap(dom(p))``.
    """

    def pullback(self, fiber: FiberValuation[T]) -> FiberValuation[T]:
        out_dom = frozenset((o, s) for (s, o) in fiber.dom)
        cells = {(o, s): v for (s, o), v in fiber.cells.items()}
        return FiberValuation(
            bilattice=fiber.bilattice,
            entities=fiber.entities,
            bottom=fiber.bottom,
            cells=cells,
            dom=out_dom,
        )

    def existential_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∃_f^k = f^*`` for converse: bijective swap, no extension.
        Singleton pre-image, join = identity."""
        return self._swap_image(fiber, target_dom)

    def universal_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∀_f^k = f^*`` for converse: same as ``∃_f^k``, meet = identity."""
        return self._swap_image(fiber, target_dom)

    def existential_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∃_f^t = f^*`` for converse. The swap is order-preserving in
        both ``≤_k`` and ``≤_t``, so the converse is self-adjoint in
        both enrichments."""
        return self._swap_image(fiber, target_dom)

    def universal_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """``∀_f^t = f^*`` for converse."""
        return self._swap_image(fiber, target_dom)

    def _swap_image(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        if target_dom != frozenset((o, s) for (s, o) in fiber.dom):
            raise ValueError(
                "converse adjoints require target_dom == swap(fiber.dom)"
            )
        cells = {(o, s): v for (s, o), v in fiber.cells.items()}
        return FiberValuation(
            bilattice=fiber.bilattice,
            entities=fiber.entities,
            bottom=fiber.bottom,
            cells=cells,
            dom=target_dom,
        )


@realizes("morphisms/predicate-subject-projection")
@dataclass(frozen=True)
class PredicateSubjectProjection(PredicateMorphism):
    """Subject-projection ``f : q -> p`` from collapse ``(s, o) ↦ (s, s)``.

    The pullback broadcasts ``p``'s subject-diagonal across the object
    coordinate: ``(f^* v)(s, o) = v(s, s)``. The output fiber's ``dom``
    is the maximal compatible set: every ``(s, o)`` such that
    ``(s, s) ∈ dom(p)`` and ``o ∈ E``.
    """

    def pullback(self, fiber: FiberValuation[T]) -> FiberValuation[T]:
        valid_subjects = {s for s in fiber.entities if (s, s) in fiber.dom}
        out_dom = frozenset(
            (s, o) for s in valid_subjects for o in fiber.entities
        )
        cells: dict[tuple[Hashable, Hashable], tuple[T, T]] = {}
        for subject in valid_subjects:
            diag = fiber.get(subject, subject)
            if diag == fiber.bottom:
                continue
            for object_ in fiber.entities:
                cells[(subject, object_)] = diag
        return FiberValuation(
            bilattice=fiber.bilattice,
            entities=fiber.entities,
            bottom=fiber.bottom,
            cells=cells,
            dom=out_dom,
        )

    def existential_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """Left adjoint of subject-projection pullback in ``≤_k``.

        ``∃_f^k(α)(s, s) = ⋁_k {α(s, o) : (s, o) ∈ dom(q)}``;
        off-diagonal cells get ``⊥_k``.
        """
        return _project_along_diagonal(
            fiber, target_dom, op="existential", axis="subject", order="k"
        )

    def universal_k(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """Right adjoint of subject-projection pullback in ``≤_k``.

        ``∀_f^k(α)(s, s) = ⋀_k {α(s, o) : (s, o) ∈ dom(q)}``;
        off-diagonal cells get ``⊤_k`` (empty meet).
        """
        return _project_along_diagonal(
            fiber, target_dom, op="universal", axis="subject", order="k"
        )

    def existential_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """Left adjoint of subject-projection pullback in ``≤_t``.

        ``∃_f^t(α)(s, s) = ⋁_t {α(s, o) : (s, o) ∈ dom(q)}``;
        off-diagonal cells get ``⊥_t = f``.
        """
        return _project_along_diagonal(
            fiber, target_dom, op="existential", axis="subject", order="t"
        )

    def universal_t(
        self,
        fiber: FiberValuation[T],
        target_dom: frozenset[tuple[Hashable, Hashable]],
    ) -> FiberValuation[T]:
        """Right adjoint of subject-projection pullback in ``≤_t``.

        ``∀_f^t(α)(s, s) = ⋀_t {α(s, o) : (s, o) ∈ dom(q)}``;
        off-diagonal cells get ``⊤_t = t`` (empty meet).
        """
        return _project_along_diagonal(
            fiber, target_dom, op="universal", axis="subject", order="t"
        )


