"""Settling-associated sheaf on a finite captured settling prefix.

The corpus object ``settling-associated-sheaf`` assigns to
``(q, tau, U)`` the free abelian group on newly-added truth-top cells of
predicate ``q`` at stage ``tau`` lying in the clopen ``U``. In this
finite executable surface, ``U`` is represented by an explicit subset of
``dom(q)`` and stages are the captured integer stages of
:class:`PredicationSettling`.
"""

from __future__ import annotations

from collections.abc import Callable, Hashable, Iterable, Mapping, Sequence
from dataclasses import dataclass
from types import MappingProxyType
from typing import Generic, TypeAlias, TypeVar, cast

from .._realizes import realizes
from ..algebra.residuated_lattice import ResiduatedLattice, boolean_residuated_lattice
from ..combinatorics.poset import Poset
from ..sheaf.q_enriched import QEnrichedSheaf
from .settling import PredicationSettling

T = TypeVar("T", bound=Hashable)
Q = TypeVar("Q", bound=Hashable)

SettlingSitePoint: TypeAlias = tuple[
    Hashable, int, frozenset[tuple[Hashable, Hashable]]
]
SettlingSiteRestriction: TypeAlias = tuple[SettlingSitePoint, SettlingSitePoint]
PredicatedCell: TypeAlias = tuple[Hashable, tuple[Hashable, Hashable]]
StagedPredicatedCell: TypeAlias = tuple[
    Hashable, int, tuple[Hashable, Hashable]
]


@dataclass(frozen=True)
class FreeAbelianCellGroup:
    """The free abelian group ``Z^basis`` represented by its cell basis."""

    basis: frozenset[tuple[Hashable, Hashable]]

    @property
    def rank(self) -> int:
        return len(self.basis)

    def zero(self) -> Mapping[tuple[Hashable, Hashable], int]:
        return MappingProxyType({cell: 0 for cell in self.basis})


@dataclass(frozen=True)
class FreeAbelianPredicationGroup:
    """Free abelian group on predicate-labelled predication cells."""

    basis: frozenset[PredicatedCell]

    @property
    def rank(self) -> int:
        return len(self.basis)

    def zero(self) -> Mapping[PredicatedCell, int]:
        return MappingProxyType({cell: 0 for cell in self.basis})


@dataclass(frozen=True)
class FreeAbelianStagedPredicationGroup:
    """Free abelian group on stage- and predicate-labelled cells."""

    basis: frozenset[StagedPredicatedCell]

    @property
    def rank(self) -> int:
        return len(self.basis)

    def zero(self) -> Mapping[StagedPredicatedCell, int]:
        return MappingProxyType({cell: 0 for cell in self.basis})


def _delta_plus_for_values(
    settling: PredicationSettling[T],
    predicate: Hashable,
    stage: int,
    values: frozenset[object],
    clopen: Iterable[tuple[Hashable, Hashable]] | None,
) -> frozenset[tuple[Hashable, Hashable]]:
    _require_stage(settling, stage)
    domain = settling.hyperdoctrine.dom(predicate)
    window = domain if clopen is None else frozenset(clopen)
    if not window <= domain:
        raise ValueError("clopen must be a subset of the predicate domain")

    current = settling.trajectory[stage][predicate]
    newly_added: set[tuple[Hashable, Hashable]] = set()
    for cell in window:
        if current.get(*cell) not in values:
            continue
        if all(
            settling.trajectory[prior][predicate].get(*cell) not in values
            for prior in range(stage)
        ):
            newly_added.add(cell)
    return frozenset(newly_added)


def _require_stage(settling: PredicationSettling[T], stage: int) -> None:
    if stage < 0 or stage >= len(settling.trajectory):
        raise IndexError(
            f"stage {stage!r} outside captured trajectory "
            f"0..{len(settling.trajectory) - 1}"
        )


@realizes("objects/settling-associated-sheaf")
@dataclass(frozen=True)
class SettlingAssociatedSheaf(Generic[T]):
    """Finite-prefix realization of the settling-associated sheaf."""

    settling: PredicationSettling[T]

    def delta_plus(
        self,
        predicate: Hashable,
        stage: int,
        clopen: Iterable[tuple[Hashable, Hashable]] | None = None,
    ) -> frozenset[tuple[Hashable, Hashable]]:
        """Newly-added truth-top cells ``Delta^+_stage(predicate) ∩ U``."""
        truth_top = self.settling.hyperdoctrine.bilattice.truth_top()
        return _delta_plus_for_values(
            self.settling,
            predicate,
            stage,
            frozenset({truth_top}),
            clopen,
        )

    def stalk(
        self,
        predicate: Hashable,
        stage: int,
        clopen: Iterable[tuple[Hashable, Hashable]] | None = None,
    ) -> FreeAbelianCellGroup:
        """Return ``Z`` freely generated by the local new truth cells."""
        return FreeAbelianCellGroup(
            basis=self.delta_plus(predicate, stage, clopen)
        )

    def rank(
        self,
        predicate: Hashable,
        stage: int,
        clopen: Iterable[tuple[Hashable, Hashable]] | None = None,
    ) -> int:
        """Rank of the free abelian group at ``(predicate, stage, clopen)``."""
        return self.stalk(predicate, stage, clopen).rank

    def stage_ranks(self, predicate: Hashable) -> tuple[int, ...]:
        """Ranks across every captured stage for one predicate."""
        return tuple(
            self.rank(predicate, stage)
            for stage in range(len(self.settling.trajectory))
        )

    def total_rank(self) -> int:
        """Total number of first-time truth-top cell firings in the prefix."""
        return sum(
            self.rank(predicate, stage)
            for predicate in self.settling.hyperdoctrine.predicates()
            for stage in range(len(self.settling.trajectory))
        )

    def _require_stage(self, stage: int) -> None:
        _require_stage(self.settling, stage)


