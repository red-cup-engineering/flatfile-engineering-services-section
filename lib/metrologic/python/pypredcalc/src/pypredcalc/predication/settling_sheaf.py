@realizes("theorems/finite-settling-h0-polynomial-time")
@dataclass(frozen=True)
class SettlingH0Witness:
    """Finite-prefix ``H^0`` witness for a settling increment sheaf.

    The basis is the predicate-labelled union of all newly designated
    cells observed in the captured trajectory. This is the executable
    finite-prefix form of the corpus statement that ``H^0`` counts the
    eventually designated support of the relevant settling sheaf.
    """

    variant: str
    bound: int
    basis: frozenset[PredicatedCell]
    staged_basis: frozenset[StagedPredicatedCell]

    @property
    def group(self) -> FreeAbelianPredicationGroup:
        return FreeAbelianPredicationGroup(self.basis)

    @property
    def rank(self) -> int:
        return self.group.rank


@dataclass(frozen=True)
class SettlingH1GeneratorCheck:
    """Validation for one supplied non-Scott-continuous firing generator."""

    requested: StagedPredicatedCell
    delta_plus: frozenset[tuple[Hashable, Hashable]]
    error: str | None = None

    @property
    def holds(self) -> bool:
        _predicate, _stage, cell = self.requested
        return self.error is None and cell in self.delta_plus


@realizes("objects/aperiodic-classifying-invariant")
@realizes("theorems/transfinite-bounded-regime-h1-generators")
@dataclass(frozen=True)
class SettlingH1Witness:
    """Finite-prefix witness for supplied ``H^1`` firing generators.

    Predication theory places ``H^1`` generators at non-Scott-continuous
    firing ordinals. A finite captured trajectory cannot infer limit
    ordinals on its own, so this witness validates caller-supplied
    generator cells against the actual finite-prefix settling-sheaf
    increments and packages the classifying invariant as the all-ones
    element on valid generators.
    """

    variant: str
    bound: int
    requested_generators: tuple[StagedPredicatedCell, ...]
    generator_basis: frozenset[StagedPredicatedCell]
    checks: tuple[SettlingH1GeneratorCheck, ...]

    @property
    def group(self) -> FreeAbelianStagedPredicationGroup:
        return FreeAbelianStagedPredicationGroup(self.generator_basis)

    @property
    def rank(self) -> int:
        return self.group.rank

    @property
    def classifying_invariant(self) -> Mapping[StagedPredicatedCell, int]:
        return MappingProxyType({generator: 1 for generator in self.generator_basis})

    @property
    def holds(self) -> bool:
        return all(check.holds for check in self.checks)

    @property
    def failures(self) -> tuple[SettlingH1GeneratorCheck, ...]:
        return tuple(check for check in self.checks if not check.holds)


@dataclass(frozen=True)
class TruthKnowledgeH0ExactnessCheck:
    """One degree-zero exactness check at a predicate-stage slice."""

    predicate: Hashable
    stage: int
    truth_cells: frozenset[tuple[Hashable, Hashable]]
    knowledge_cells: frozenset[tuple[Hashable, Hashable]]
    inconsistency_cells: frozenset[tuple[Hashable, Hashable]]

    @property
    def holds(self) -> bool:
        return (
            self.truth_cells.isdisjoint(self.inconsistency_cells)
            and self.knowledge_cells
            == self.truth_cells | self.inconsistency_cells
        )


@realizes("theorems/truth-knowledge-cohomology-long-exact-sequence")
@dataclass(frozen=True)
class TruthKnowledgeH0SequenceWitness(Generic[T]):
    """Degree-zero shadow of the truth/knowledge long exact sequence."""

    settling: PredicationSettling[T]
    truth_h0: SettlingH0Witness
    knowledge_h0: SettlingH0Witness
    inconsistency_h0: SettlingH0Witness
    checks: tuple[TruthKnowledgeH0ExactnessCheck, ...]

    @property
    def holds(self) -> bool:
        return all(check.holds for check in self.checks)

    @property
    def failures(self) -> tuple[TruthKnowledgeH0ExactnessCheck, ...]:
        return tuple(check for check in self.checks if not check.holds)


@realizes("objects/bigraded-settling-cohomology")
@realizes("theorems/bigraded-cohomology-via-mapping-cone")
@dataclass(frozen=True)
class BigradedSettlingCohomologyWitness(Generic[T]):
    """Finite degree-zero bigraded settling cohomology witness.

    The finite SDK surface records the two non-zero designation rows from the
    corpus bicomplex: row ``m=0`` for truth-designated increments and row
    ``m=1`` for TOP/inconsistency increments. ``knowledge_h0`` is retained as
    the paraconsistent extension row that the long exact sequence factors
    through.
    """

    settling: PredicationSettling[T]
    truth_h0: SettlingH0Witness
    knowledge_h0: SettlingH0Witness
    inconsistency_h0: SettlingH0Witness
    exact_sequence: TruthKnowledgeH0SequenceWitness[T]

    @property
    def row_ranks(self) -> tuple[tuple[int, int, int], ...]:
        """Return ``(designation_grade, cohomological_degree, rank)`` rows."""
        return (
            (0, 0, self.truth_h0.rank),
            (1, 0, self.inconsistency_h0.rank),
        )

    @property
    def total_degree_zero_rank(self) -> int:
        return self.truth_h0.rank + self.inconsistency_h0.rank

    @property
    def extension_rank(self) -> int:
        return self.knowledge_h0.rank

    @property
    def holds(self) -> bool:
        return self.exact_sequence.holds

    def __bool__(self) -> bool:
        return self.holds


