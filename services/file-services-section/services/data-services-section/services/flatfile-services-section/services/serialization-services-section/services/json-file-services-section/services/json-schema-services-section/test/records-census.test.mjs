import assert from "node:assert/strict";
import test from "node:test";
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { censusRecords, recordKindDeclaration, recordKindOfPath } from "../src/census.mts";

const entry = (path, blob, bytes, extra = {}) => ({ path, blob, bytes, head: "", ...extra });

test("record kinds are keyed by the first segment after data/records, loose files by extension", () => {
  assert.deepEqual(recordKindOfPath("a/b/data/records/editions/x/y.json"), { root: "a/b/data/records/", kind: "editions", directory: "a/b/data/records/editions" });
  assert.deepEqual(recordKindOfPath("data/records/ledger.beancount"), { root: "data/records/", kind: "(root).beancount", directory: "data/records/" });
  assert.equal(recordKindOfPath("a/data/recordsx/y.json"), null);
  assert.equal(recordKindOfPath("a/src/data.json"), null);
});

test("records census counts files, bytes, derivable, duplicate, code and schema readings per kind in FOUR", () => {
  const result = censusRecords([
    entry("s1/data/records/knowledge/README.md", "r", 40, { content: "Nothing here is edited by hand; regenerate it from the corpus." }),
    entry("s1/data/records/knowledge/census.json", "k", 100),
    entry("s1/data/records/ledger.beancount", "l", 500, { head: "; Generated by derive-ledger. Do not hand-edit.\n" }),
    entry("s1/data/records/cover-lab/concept-set.json", "dup", 30),
    entry("s1/data/records/cover-lab/evidence/T/h.json", "dup", 30),
    entry("s2/data/records/econ/scripts/fetch.mjs", "c", 10),
    entry("s2/data/records/schema/thing.schema.json", "s1", 20, { content: '{"type":"object"}' }),
    entry("s2/data/records/schema/kept.schema.json", "s2", 20, { content: '{"x-codegen":{},"type":"object"}' }),
    entry("s2/src/not-a-record.json", "n", 999),
  ]);
  assert.equal(result.totals.files, 8);
  assert.equal(result.totals.bytes, 750);
  assert.equal(result.totals.recordsDirectories, 2);
  assert.equal(result.totals.kindDirectories, 4);
  assert.equal(result.totals.duplicateGroups, 1);
  assert.equal(result.totals.duplicateBytes, 30);
  assert.equal(result.totals.schemaFiles, 2);
  assert.equal(result.totals.schemasWithoutCodegen, 1);
  assert.equal(result.totals.codeFiles, 1);
  assert.equal(result.totals.derivableBytes, 600);
  const kind = (name) => result.kinds.find((item) => item.kind === name);
  assert.deepEqual([kind("knowledge").derivableBytes, kind("knowledge").inferredClass], [100, "derivation"]);
  assert.equal(kind("(root).beancount").readings["no-derivable-bytes"], "f");
  assert.deepEqual([kind("cover-lab").duplicateFiles, kind("cover-lab").readings["no-duplicate-bytes"]], [1, "f"]);
  assert.deepEqual([kind("econ").codeFiles, kind("econ").readings["no-code"], kind("econ").inferredClass], [1, "f", "code"]);
  assert.equal(kind("schema").readings["schema-consumed"], "⊤");
  for (const item of result.kinds) { assert.equal(item.readings.declared, "⊥"); assert.equal(item.readings["has-reader"], "⊥"); assert.equal(item.readerCount, 0); }
  assert.equal(result.totals.kindsWithoutReader, result.kinds.length);
  assert.deepEqual(result.readingCounts.declared, { "⊥": 5, t: 0, f: 0, "⊤": 0 });
});

test("x-codegen declarations settle declared and has-reader, and two declarations are contested", () => {
  const declare = (path, body) => recordKindDeclaration(path, JSON.stringify({ "x-codegen": {}, ...body }));
  assert.equal(recordKindDeclaration("a.schema.json", '{"x-record-kind":"editions"}'), null);
  assert.equal(recordKindDeclaration("a.schema.json", "not json"), null);
  const files = [entry("s/data/records/editions/a.json", "a", 1), entry("s/data/records/cover-lab/b.json", "b", 1), entry("s/data/records/receipts/c.json", "c", 1), entry("s/data/records/ledger/d.json", "d", 1, { head: "Generated by x" })];
  const result = censusRecords(files, [
    declare("e.schema.json", { "x-record-kind": "editions", "x-record-class": "act", "x-record-readers": ["admitEdition", "admitEdition"] }),
    declare("c1.schema.json", { "x-record-kind": "cover-lab", "x-record-class": "observation" }),
    declare("c2.schema.json", { "x-record-kind": "cover-lab", "x-record-class": "observation" }),
    declare("r.schema.json", { "x-record-kind": "receipts", "x-record-class": "receipt", "x-record-readers": [] }),
    declare("l.schema.json", { "x-record-kind": "ledger", "x-record-class": "authored", "x-record-readers": ["readLedger"] }),
  ]);
  const kind = (name) => result.kinds.find((item) => item.kind === name);
  assert.deepEqual([kind("editions").readings.declared, kind("editions").readings["has-reader"], kind("editions").readerCount, kind("editions").declaredClass], ["t", "t", 1, "act"]);
  assert.equal(kind("cover-lab").readings.declared, "⊤");
  assert.deepEqual([kind("receipts").readings.declared, kind("receipts").readings["has-reader"]], ["⊤", "f"]);
  assert.equal(kind("ledger").readings["no-derivable-bytes"], "⊤");
  assert.equal(result.totals.kindsWithoutReader, 2);
});

test("json-schema-census --records reads git ls-files, not the working tree", () => {
  const root = mkdtempSync(join(tmpdir(), "records-census-"));
  try {
    const write = (path, text) => { mkdirSync(dirname(join(root, path)), { recursive: true }); writeFileSync(join(root, path), text); };
    const git = (...args) => execFileSync("git", ["-C", root, ...args], { encoding: "utf8" });
    git("init", "-q");
    write("s/data/records/kind/a.json", "{}\n");
    write("s/data/records/kind/b.json", "{}\n");
    git("add", ".");
    write("s/data/records/kind/untracked.json", "{\"x\":1}\n");
    const script = resolve(dirname(fileURLToPath(import.meta.url)), "../scripts/json-schema-census.mjs");
    const result = JSON.parse(execFileSync(process.execPath, [...process.execArgv.filter((flag) => !flag.startsWith("--test")), script, "--records", "--root", root], { encoding: "utf8" }));
    assert.deepEqual([result.source, result.commit], ["git ls-files", null]);
    assert.deepEqual([result.totals.files, result.totals.bytes, result.totals.duplicateGroups, result.totals.duplicateBytes], [2, 6, 1, 3]);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
